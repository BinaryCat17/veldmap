//! Очередь найденных мест: на вопрос «где на экране этот элемент» отвечает
//! тот, кто разметку рисует, а забирает ответ кадровый цикл раннера. Устроена
//! как очередь поверхностей (surfaces.rs) и по той же причине: у неё два
//! потребителя по разные стороны шины, и ни одному из них она не принадлежит.
//!
//! Прав здесь не проверяют, и это не потому, что ответ безобиден — из него
//! раннер синтезирует настоящее нажатие. Проверять просто нечем: кому
//! делегирована поверхность окна, знает владелец окна, а не хост
//! (делегирование идёт модуль модулю), и «вправе ли этот отвечать» хосту не из
//! чего вывести. Держится это на том, что вопрос задаёт только сам хост и
//! только по сценарию: без него ответы никто не читает.

use dashmap::DashMap;

/// Место элемента и то, чем оно доказано.
#[derive(Clone, Copy)]
pub struct Place {
    /// Номер вопроса, на который это ответ.
    pub request: u64,
    /// Сколько элементов подошло под вопрос.
    pub found: u32,
    /// Прямоугольник названного, в физических пикселях окна.
    pub x: f32,
    pub y: f32,
    pub width: f32,
    pub height: f32,
}

/// Ключ — имя владельца окна (оно же plugin_id в контракте app).
#[derive(Default)]
pub struct PlaceQueue {
    answered: DashMap<String, Place>,
}

impl PlaceQueue {
    pub fn new() -> Self {
        Self::default()
    }

    /// Ответ на более свежий вопрос вытесняет прежний: спрашивающему нужен
    /// ответ на последний вопрос, а прежние он всё равно отбросит. Обратное
    /// вытеснение запрещено здесь, а не дисциплиной спрашивающего: запоздалый
    /// ответ, легший поверх нужного, был бы неотличим от молчания.
    pub fn answer(&self, owner: &str, place: Place) {
        self.answered
            .entry(owner.to_string())
            .and_modify(|kept| {
                if place.request >= kept.request {
                    *kept = place;
                }
            })
            .or_insert(place);
    }

    /// Забирает ответ владельцу — раз в кадр, из цикла раннера.
    pub fn take(&self, owner: &str) -> Option<Place> {
        self.answered.remove(owner).map(|(_, place)| place)
    }
}
