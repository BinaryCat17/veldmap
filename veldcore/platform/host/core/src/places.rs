//! Очередь найденных мест: рендерер отвечает, где на экране элемент, а
//! забирает ответ кадровый цикл раннера. Устроена как очередь поверхностей
//! (surfaces.rs) и по той же причине: у неё два потребителя по разные стороны
//! шины, и ни одному из них она не принадлежит.
//!
//! Политики здесь нет — ни прав, ни проверки, кто отвечает. Фасада поэтому
//! тоже нет: ответом ничего не распоряжаются, им только называют
//! прямоугольник, а спрашивает всегда сам хост.

use dashmap::DashMap;

/// Место элемента и то, чем оно доказано.
#[derive(Clone, Copy)]
pub struct Place {
    /// Номер вопроса, на который это ответ.
    pub request: u64,
    /// Сколько элементов подошло под вопрос.
    pub found: u32,
    /// Прямоугольник названного, в физических пикселях окна.
    pub x: f32,
    pub y: f32,
    pub width: f32,
    pub height: f32,
}

/// Ключ — имя владельца окна (оно же plugin_id в контракте app).
#[derive(Default)]
pub struct PlaceQueue {
    answered: DashMap<String, Place>,
}

impl PlaceQueue {
    pub fn new() -> Self {
        Self::default()
    }

    /// Ответ вытесняет предыдущий: вопрос задаётся по одному за раз, и
    /// пришедший позже отвечает на более свежий.
    pub fn answer(&self, owner: &str, place: Place) {
        self.answered.insert(owner.to_string(), place);
    }

    /// Забирает ответ владельцу — раз в кадр, из цикла раннера.
    pub fn take(&self, owner: &str) -> Option<Place> {
        self.answered.remove(owner).map(|(_, place)| place)
    }
}
