//! Очередь поверхностей окон: владелец окна аттачит текстуру, кадровый цикл
//! раннера её забирает. Состояние — как реестр задач (tasks.rs): голая
//! таблица без политики. Проверки прав (владение окном, write-lease на
//! текстуру) делает фасад Surfaces (host-util); раннер только дренирует.
//!
//! Свап отложен намеренно: аттач приходит из актор-очереди диспетчера в
//! произвольный момент, а подменять текстуру можно только между кадрами.

use dashmap::DashMap;

/// Ключ — имя владельца окна (оно же plugin_id в контракте app).
/// Значение — id региона текстуры, ожидающей аттача.
#[derive(Default)]
pub struct SurfaceQueue {
    pending: DashMap<String, u64>,
}

impl SurfaceQueue {
    pub fn new() -> Self {
        Self::default()
    }

    /// Ставит поверхность в очередь на аттач. Повторный аттач до того, как
    /// кадровый цикл забрал предыдущий, вытесняет его: показать всё равно
    /// можно только последнюю, а промежуточные кадру не нужны.
    pub fn attach(&self, owner: &str, texture_id: u64) {
        self.pending.insert(owner.to_string(), texture_id);
    }

    /// Забирает ожидающую поверхность владельца, если она есть.
    /// Вызывается кадровым циклом раннера ровно один раз на кадр.
    pub fn take(&self, owner: &str) -> Option<u64> {
        self.pending.remove(owner).map(|(_, id)| id)
    }
}
