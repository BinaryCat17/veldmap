//! Наблюдатель убийства для длинной работы внутри одного обработчика.
//!
//! Со стороны заказчика делать нечего: операцию завёл и закроет хост по самим
//! публикациям запроса и ответа, а убивает её заказчик одним стабом
//! (`tasks/on_cancel`). Обрядов вокруг этого больше нет — учитывать нечего.

/// «Меня ещё ждут?» — вопрос, который шиной не отвечается по построению.
///
/// Пока обработчик не вернул управление, очередь модуля не разгребается:
/// событие об убийстве придёт уже после той работы, которую должно было
/// прервать. Поэтому исполнитель опрашивает `cancelled()` между порциями
/// работы — чтением чанка, декодированием полосы. Это единственное, ради чего
/// у системы задач есть ABI.
///
/// Учёт операции открыт до того, как запрос доставлен: диспетчер заводит его
/// на публикации, а доставка идёт следом (см. dispatcher::account). Значит к
/// первому опросу запись уже есть, и «не жива» означает ровно одно — убили.
/// Гадать, не запоздал ли учёт, больше не нужно.
pub struct Cancellation {
    task_id: String,
}

impl Cancellation {
    /// `task_id` — корреляция исполняемого запроса (`veldsdk::correlation()`):
    /// под ней операция учтена, ею же заказчик её убьёт.
    pub fn watch(task_id: &str) -> Self {
        Self { task_id: task_id.to_string() }
    }

    /// Операцию убили — работу пора прекращать.
    pub fn cancelled(&self) -> bool {
        !crate::abi::task_alive(&self.task_id)
    }
}
