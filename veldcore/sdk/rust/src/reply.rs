//! Ответ, которого исполнитель не давал: терминал, договорённый хостом.
//!
//! Вопрос один на всех, кто ждёт ответа, и на оба рода терминалов — с полем
//! ошибки и без него, — и правило поэтому одно: разойдясь, канва, шар, кэш и
//! библиотека вели бы себя над одной и той же бедой по-разному. Что такое
//! договорённый ответ и когда он приходит — `docs/architecture/bus-and-schema.md`.

/// Терминальный ответ, договорённый хостом, — это отказ, а не успех.
///
/// Пустой ответ читается как удача: у `QueryDone` пустые промахи значат «всё
/// нашлось», у `ProduceDone` пустая ошибка — «прошло», у `SignedUrl` — «адрес
/// подписан». А договаривает его хост там, где исполнитель умер посреди
/// работы, где операцию сняли либо где подписчика у запроса не нашлось вовсе;
/// заказчик, принявший это за удачу, снимает с ожидания ячейки, которых никто
/// не привозил, или шлёт закачку по пустому адресу.
///
/// Отличает такой ответ отправитель: имя есть у всякого зарегистрированного
/// сервиса, нативного наравне с wasm, а договорённое за исполнителя хост
/// публикует без имени по построению. Окно, в котором это шире буквального:
/// имя сервиса ядро заносит в реестр последним шагом загрузки, уже после
/// `init`, так что событие, опубликованное из `init`, приехало бы безымянным
/// при живом отправителе. Терминальным ответом оно не бывает — в `init`
/// отвечать не на что, — но спрашивать это на прочих событиях по той же
/// причине нельзя.
///
/// Снятое заказчиком сюда попадает наравне с упавшим: хост договаривает то и
/// другое одинаково, и различить их может только снимавший — по своей памяти.
///
/// `None` — ответ настоящий, каким бы он ни был: непустая причина сказана
/// исполнителем до смерти и своего смысла не теряет.
pub fn undelivered(error: &str) -> Option<String> {
    (error.is_empty() && crate::abi::answered_by_host())
        .then(|| "исполнитель не довёл работу: ответ договорил хост".to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Договорённый хостом терминальный ответ — отказ, а не успех, и узнаётся
    /// он по отправителю, а не по содержимому: пустой ответ от исполнителя —
    /// настоящий.
    #[test]
    fn a_settled_reply_is_not_a_success() {
        crate::abi::set_event_context("tile-cache".to_string(), "c".to_string(), false);
        assert_eq!(undelivered(""), None, "ответ от самого исполнителя — настоящий");
        assert_eq!(undelivered("кэш отказал"), None, "у настоящего отказа своя причина");

        crate::abi::set_event_context(String::new(), "c".to_string(), false);
        assert!(undelivered("").is_some(), "пустой ответ от хоста — недоведённая работа");
        assert_eq!(
            undelivered("кэш отказал"),
            None,
            "непустая причина сказана исполнителем до смерти и своего смысла не теряет"
        );
    }
}
