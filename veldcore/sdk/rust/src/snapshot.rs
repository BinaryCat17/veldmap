//! Рассылка снимка состояния: не слать неизменившееся.
//!
//! Топик, объявленный в схеме `snapshot: true`, везёт состояние целиком —
//! чего не прислали, того у подписчика больше нет. У такой рассылки много
//! вызывающих: её делает всякое изменение того, о чём она рассказывает, — и
//! каждый из них обязан был бы спросить «а изменилось ли», иначе подписчик
//! получает то же самое десятки раз в секунду. Условие поэтому стоит не у
//! них, а в сгенерированном стабе топика: забыть его негде, и двум его
//! экземплярам негде разойтись.
//!
//! Отправитель помнит одно число на топик — отпечаток последнего
//! отправленного тела. Ноль означает «ещё ничего не слали»: свежий инстанс —
//! в том числе поднятый заново после убийства — начинает с нуля и первую
//! рассылку делает непременно.
//!
//! Помнит именно отправитель, и отсюда единственное правило контракта:
//! подписчик снимка не вправе терять своё состояние. Убитый и поднятый заново
//! потерял бы его молча, а отправитель об этом не знает и повтора не сделает —
//! поэтому схема не сводит `snapshot: true` с отменяемым потребителем
//! (проверку держит buildgen). Спрошенный же заново снимок — дело обычное, и
//! на него есть `crate::emit::resend::<топик>()`: он забывает отпечаток, и
//! следующая рассылка уходит, совпади она хоть дословно.

use core::sync::atomic::{AtomicU64, Ordering};

/// Отличается ли тело от последнего отправленного по этому топику. `true` —
/// отличается, и отпечаток тут же переписан на новый: спрашивают об этом
/// ровно перед публикацией, и второго ответа между вопросом и отправкой быть
/// не должно.
pub fn changed(last: &AtomicU64, body: &[u8]) -> bool {
    let mark = fingerprint(body);
    if last.load(Ordering::Relaxed) == mark {
        return false;
    }
    last.store(mark, Ordering::Relaxed);
    true
}

/// Забыть отправленное: следующая рассылка уйдёт, даже если тело совпадёт с
/// прежним. Так отвечают на просьбу прислать состояние заново — у
/// спрашивающего его нет, и «не изменилось» означало бы «не ответим вовсе».
pub fn forget(last: &AtomicU64) {
    last.store(0, Ordering::Relaxed);
}

/// Отпечаток тела. Ноль занят под «ещё не слали», поэтому наружу не выходит:
/// совпавший с ним отпечаток подавил бы первую же рассылку.
fn fingerprint(body: &[u8]) -> u64 {
    use std::hash::{Hash, Hasher};
    let mut hasher = std::collections::hash_map::DefaultHasher::new();
    body.hash(&mut hasher);
    match hasher.finish() {
        0 => 1,
        mark => mark,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Первая рассылка уходит всегда, повтор того же тела — нет, изменившееся
    /// снова уходит.
    #[test]
    fn only_a_different_body_goes_out() {
        let last = AtomicU64::new(0);
        assert!(changed(&last, b"one"), "первая рассылка");
        assert!(!changed(&last, b"one"), "то же тело");
        assert!(changed(&last, b"two"), "другое тело");
        assert!(!changed(&last, b"two"));
        assert!(changed(&last, b"one"), "вернувшееся прежнее тело — тоже смена");
    }

    /// Забытый отпечаток возвращает топик в состояние «ещё не слали»: тем и
    /// отвечают на просьбу прислать состояние заново.
    #[test]
    fn forgetting_lets_the_same_body_out_again() {
        let last = AtomicU64::new(0);
        assert!(changed(&last, b"one"));
        assert!(!changed(&last, b"one"));
        forget(&last);
        assert!(changed(&last, b"one"), "после forget уходит дословно то же");
    }

    /// Пустое тело — обычное тело: у топика без содержательных полей рассылка
    /// «состояние стало пустым» ничем не хуже прочих.
    #[test]
    fn an_empty_body_is_a_body() {
        let last = AtomicU64::new(0);
        assert!(changed(&last, b""), "первая рассылка пустого");
        assert!(!changed(&last, b""));
        assert!(changed(&last, b"x"));
        assert!(changed(&last, b""), "возврат к пустому — тоже смена");
    }

    /// Ноль означает «ещё не слали», поэтому отпечатком он не бывает: иначе
    /// тело, попавшее в него хэшем, не уехало бы ни разу.
    #[test]
    fn a_fingerprint_is_never_the_never_sent_mark() {
        for body in [b"".as_slice(), b"a", "состояние".as_bytes(), &[0u8; 64]] {
            assert_ne!(fingerprint(body), 0);
        }
    }
}
