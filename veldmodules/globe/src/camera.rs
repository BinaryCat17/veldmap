//! Камера над Землёй и матрицы, которые из неё выводятся.
//!
//! Камера — это географическая точка: она висит над (широта, долгота) на
//! высоте и смотрит в центр эллипсоида. Отдельных «углов орбиты» у неё нет
//! намеренно — это те же координаты, в которых приходит вся остальная
//! геометрия, и переход к декартовым у них общий (`geodesy::position`).
//!
//! Земля при этом неподвижна: у неё есть собственная система координат, и
//! вращать надо было бы её вместе с ней — а тогда «что за точка под курсором»
//! перестало бы быть вопросом к одной матрице.
//!
//! ## Всё меряется тем, что видно
//!
//! Высота сама по себе не значит ничего: и жест, и наводка на место говорят об
//! угле — сколько дуги умещается в кадре. Эту величину считает
//! [`Camera::visible_deg`], и она же, обращённая, отвечает на вопрос «с какой
//! высоты видно вот столько» ([`height_for`]). Отсюда и главное свойство
//! управления: протаскивание на всю высоту области поворачивает ровно на то,
//! что в ней видно, — на любой высоте.
//!
//! Матричная арифметика здесь своя и ровно на три операции. Библиотека линейной
//! алгебры дала бы то же самое, но своей зависимостью — а весь долг перед ней
//! составляет полсотни строк, которые больше не изменятся.

use crate::module::geodesy::{self, Geodetic};

/// Матрица 4×4 в раскладке WGSL: по столбцам, элемент `[col * 4 + row]`.
pub type Mat4 = [f32; 16];

/// Вектор внутренних выкладок — f64, как и вся геометрия Земли (см.
/// `geodesy`). Наружу, в вершинный буфер и в uniform, уезжает f32.
type Vec3 = [f64; 3];

/// Северный полюс — он же «верх» кадра. Ось Z в ECEF (см. `geodesy`).
const NORTH: Vec3 = [0.0, 0.0, 1.0];

/// Вертикальный угол обзора. Им меряется не только проекция: жест и наводка
/// считают через него, сколько дуги в кадре, — поэтому он один на всех.
const FOV_Y_DEG: f64 = 50.0;

/// Во сколько раз приближает один щелчок колеса.
const ZOOM_PER_STEP: f64 = 0.88;

/// Высота над эллипсоидом: от низкой орбиты до вида, где Земля — шарик.
const HEIGHT_RANGE_M: (f64, f64) = (100_000.0, 80_000_000.0);

/// Насколько близко к полюсу пускаем камеру. Ровно над полюсом взгляд сходится
/// с направлением на север, и повороту кадра не от чего отсчитываться.
const MAX_LAT_DEG: f64 = 89.0;

/// Насколько сильно разрешено разгонять долготу у полюса. Разгон нужен, чтобы
/// земля шла за курсором: параллель там короче экватора во столько же раз, во
/// сколько меньше её косинус, — но на самом полюсе он обращается в ноль, и без
/// потолка жест сорвался бы в неуправляемую крутку.
const MAX_LON_GAIN: f64 = 4.0;

/// Запас вокруг наведённого: контур, упирающийся в край кадра, читается как
/// обрезанный.
const FRAME_MARGIN: f64 = 1.3;

#[derive(Clone, Copy, PartialEq)]
pub struct Camera {
    /// Где висит камера. Высота считается от поверхности эллипсоида, поэтому
    /// «100 км» означает 100 км и над экватором, и над полюсом.
    at: Geodetic,
}

impl Default for Camera {
    /// Начальный вид — Евразия целиком: то, ради чего приложение и открывают.
    fn default() -> Self {
        Self { at: Geodetic { lat_deg: 45.0, lon_deg: 60.0, height_m: 14_000_000.0 } }
    }
}

impl Camera {
    /// Протаскивание: Земля едет за курсором. Отсюда и знак у долготы — камера
    /// движется навстречу жесту, а не вместе с ним.
    ///
    /// Доля области переводится в градусы по тому, что в области видно: на
    /// отлёте это сотня градусов, у самой поверхности — доли градуса. Постоянный
    /// темп сгодился бы ровно для одной высоты, а на всех остальных жест был бы
    /// либо вязким, либо срывающимся.
    pub fn orbit(&mut self, dx: f32, dy: f32) {
        // Во всю высоту области видно вдвое больше, чем от центра до края.
        let span = 2.0 * self.visible_deg();
        let gain = (1.0 / self.at.lat_deg.to_radians().cos()).min(MAX_LON_GAIN);

        let lon = self.at.lon_deg - dx as f64 * span * gain;
        // Долгота сворачивается в −180..180, а не копится: за долгую возню она
        // ушла бы в тысячи градусов, и точность f64 тратилась бы на витки.
        self.at.lon_deg = lon - 360.0 * ((lon + 180.0) / 360.0).floor();
        self.at.lat_deg = (self.at.lat_deg + dy as f64 * span).clamp(-MAX_LAT_DEG, MAX_LAT_DEG);
    }

    pub fn zoom(&mut self, steps: f32) {
        self.at.height_m = (self.at.height_m * ZOOM_PER_STEP.powf(steps as f64))
            .clamp(HEIGHT_RANGE_M.0, HEIGHT_RANGE_M.1);
    }

    /// Навести камеру на место так, чтобы вокруг него было видно круг заданного
    /// углового радиуса.
    pub fn focus(&mut self, lat_deg: f64, lon_deg: f64, radius_deg: f64) {
        self.at.lat_deg = lat_deg.clamp(-MAX_LAT_DEG, MAX_LAT_DEG);
        self.at.lon_deg = lon_deg;
        self.at.height_m =
            height_for(radius_deg * FRAME_MARGIN).clamp(HEIGHT_RANGE_M.0, HEIGHT_RANGE_M.1);
    }

    /// Угловой радиус видимого: сколько градусов дуги отделяют точку под
    /// камерой от края кадра по вертикали.
    ///
    /// Луч под углом `α` к оси взгляда встречает поверхность там, где сходятся
    /// три отрезка — от центра до камеры, от центра до точки и сам луч; по
    /// теореме синусов угол при точке равен `asin(r · sin α)`, а искомая дуга —
    /// то, что осталось от развёрнутого угла.
    ///
    /// Сжатием эллипсоида здесь пренебрегаем: на темпе жеста его треть процента
    /// не видна, а честный счёт потребовал бы знать, в какую сторону ведёт
    /// жест.
    fn visible_deg(&self) -> f64 {
        let half = (FOV_Y_DEG * 0.5).to_radians();
        let sine = self.radius() * half.sin();
        if sine >= 1.0 {
            // Край кадра мимо Земли: тогда её видно до горизонта, и дальше него
            // ничего нет.
            (1.0 / self.radius()).acos().to_degrees()
        } else {
            (sine.asin() - half).to_degrees()
        }
    }

    /// Насколько камера удалена от центра, в экваториальных радиусах, — мера, в
    /// которой считается вся геометрия вида.
    fn radius(&self) -> f64 {
        1.0 + self.at.height_m / geodesy::SEMI_MAJOR_M
    }

    pub fn eye(&self) -> geodesy::World {
        geodesy::position(self.at)
    }

    /// Куда смотрит точка кадра, долями области: (0, 0) — левый верхний угол.
    /// Отдаёт луч — начало и направление; во что он упирается, знает `geodesy`.
    ///
    /// Обратное к проекции, но не обращением матрицы: базис камеры известен и
    /// без неё, а обратная матрица 4×4 — это ещё полсотни строк, которые
    /// сойдутся с прямой только на глаз.
    pub fn ray(&self, x: f32, y: f32, aspect: f32) -> (Vec3, Vec3) {
        let (side, up, forward) = self.basis();
        // Кадр отстоит от камеры на единицу вдоль взгляда, поэтому полкадра по
        // вертикали — это тангенс половины угла обзора, а по горизонтали он же,
        // растянутый пропорциями области.
        let half = (FOV_Y_DEG * 0.5).to_radians().tan();
        let right = (2.0 * x as f64 - 1.0) * half * aspect as f64;
        // Ось Y кадра смотрит вверх, а доли области считаются сверху вниз.
        let above = (1.0 - 2.0 * y as f64) * half;

        let direction = normalize([
            forward[0] + side[0] * right + up[0] * above,
            forward[1] + side[1] * right + up[1] * above,
            forward[2] + side[2] * right + up[2] * above,
        ]);
        (geodesy::world(self.at), direction)
    }

    /// Плоскости отсечения выводятся из высоты, а не заданы числами: на близком
    /// подлёте фиксированная ближняя плоскость съедает почти всю точность
    /// глубины, а на отлёте дальняя обрезала бы Землю.
    pub fn view_projection(&self, aspect: f32) -> Mat4 {
        let near = geodesy::metres(self.at.height_m) * 0.5;
        // Дальний край эллипсоида не дальше, чем |eye| + большая полуось.
        let far = self.radius() as f32 + 1.05;
        multiply(
            &perspective((FOV_Y_DEG as f32).to_radians(), aspect.max(0.01), near, far),
            &look_at(geodesy::world(self.at), self.basis()),
        )
    }

    /// Оси кадра: вправо, вверх и вперёд. Одни на всех, кому нужна ориентация
    /// камеры, — матрицу вида и луч под курсором иначе пришлось бы выводить
    /// порознь, а сойтись им обязательно.
    fn basis(&self) -> (Vec3, Vec3, Vec3) {
        let eye = geodesy::world(self.at);
        let forward = normalize([-eye[0], -eye[1], -eye[2]]);
        let side = normalize(cross(forward, NORTH));
        (side, cross(side, forward), forward)
    }
}

/// Высота, с которой видно круг такого углового радиуса, — обратное к
/// [`Camera::visible_deg`].
///
/// Мерой берётся вертикаль: угол обзора задан по ней, а место под шар шире, чем
/// выше, поэтому поместившееся по вертикали помещается и поперёк.
fn height_for(radius_deg: f64) -> f64 {
    let half = (FOV_Y_DEG * 0.5).to_radians();
    // Дальше горизонта кадр не растянуть: за ним Земля уходит от взгляда, а не
    // прибавляется, — отсюда и потолок.
    let arc = radius_deg.clamp(0.0, 89.0).to_radians();
    let radius = if arc + half >= std::f64::consts::FRAC_PI_2 {
        1.0 / arc.cos()
    } else {
        (arc + half).sin() / half.sin()
    };
    (radius - 1.0) * geodesy::SEMI_MAJOR_M
}

/// Перспектива с диапазоном глубины 0..1 — тем, который ждёт wgpu (в отличие
/// от -1..1 у OpenGL).
fn perspective(fov_y: f32, aspect: f32, near: f32, far: f32) -> Mat4 {
    let f = 1.0 / (fov_y * 0.5).tan();
    let range = 1.0 / (near - far);
    [
        f / aspect, 0.0, 0.0, 0.0,
        0.0, f, 0.0, 0.0,
        0.0, 0.0, far * range, -1.0,
        0.0, 0.0, near * far * range, 0.0,
    ]
}

/// Взгляд из точки по готовым осям кадра. В f32 переводится здесь и только
/// здесь: дальше матрица уезжает в шейдер, где другой точности и нет.
fn look_at(eye: Vec3, (side, up, forward): (Vec3, Vec3, Vec3)) -> Mat4 {
    [
        side[0] as f32, up[0] as f32, -forward[0] as f32, 0.0,
        side[1] as f32, up[1] as f32, -forward[1] as f32, 0.0,
        side[2] as f32, up[2] as f32, -forward[2] as f32, 0.0,
        -dot(side, eye) as f32, -dot(up, eye) as f32, dot(forward, eye) as f32, 1.0,
    ]
}

fn multiply(a: &Mat4, b: &Mat4) -> Mat4 {
    let mut out = [0.0; 16];
    for col in 0..4 {
        for row in 0..4 {
            out[col * 4 + row] = (0..4).map(|k| a[k * 4 + row] * b[col * 4 + k]).sum();
        }
    }
    out
}

fn dot(a: Vec3, b: Vec3) -> f64 { a[0] * b[0] + a[1] * b[1] + a[2] * b[2] }

fn cross(a: Vec3, b: Vec3) -> Vec3 {
    [
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    ]
}

fn normalize(v: Vec3) -> Vec3 {
    let len = dot(v, v).sqrt();
    if len == 0.0 { v } else { [v[0] / len, v[1] / len, v[2] / len] }
}
