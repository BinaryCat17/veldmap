//! Шаг колеса — один на шар и канву просмотра.
//!
//! Файл включён дважды: модулем (`crate::module::wheel`) и wrap-крейтом
//! (`veldmap_globe_wrap::wheel`, через `#[path]` в wrap.rs), откуда его берёт
//! data-browser для канвы. Колесо одно, и щелчок у него один: два разных шага
//! — это то, чего пользователю неоткуда узнать, а два сведённых числа держатся
//! только пока их кто-то сводит.

/// Во сколько раз один щелчок колеса меняет масштаб канвы просмотра.
pub const ZOOM_PER_CLICK: f64 = 1.25;

/// Во сколько раз один щелчок меняет высоту камеры шара — обратно шагу канвы:
/// у канвы больше значит крупнее, у шара ближе значит ниже.
pub const ZOOM_PER_STEP: f64 = 1.0 / ZOOM_PER_CLICK;
