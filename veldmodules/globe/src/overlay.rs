        let mut nodes = Vec::new();
        for row in 0..3 {
            for col in 0..3 {
                let (fx, fy) = (f64::from(col) * 0.5, f64::from(row) * 0.5);
                nodes.push(tie(fx, fy, 10.0 - fy, 20.0 + fx));
            }
        }
        assert!(Grid::new(&nodes).expect("решётка 3×3").is_dense());
