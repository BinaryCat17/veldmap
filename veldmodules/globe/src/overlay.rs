    /// Решётка по долям растра — ещё не привязка: у трека надирного прибора
    /// поперёк протяжённости нет вовсе, и на Земле такая «решётка» ложится
    /// линией. Квады по ней нулевой площади, а её ширина делит выбор уровня.
