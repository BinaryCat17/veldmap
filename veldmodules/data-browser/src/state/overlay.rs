//! Наложение снимка на шар: что собирается и что уже показано.
//!
//! Наложение одно: показывают выбранный продукт, и новый «Показать на шаре»
//! заменяет прежний. Сборка идёт в три такта — растры у провайдера, открытие
//! каждого ресурсом, передача владения глобусу, — и всё это переживает
//! обработчики, поэтому живёт здесь, а не в локальных переменных.

use veldsdk::proto::core::ResourceHandle;

use crate::proto::data_provider::UtmFrame;
use super::ViewId;

pub struct OverlayState {
    /// Продукт наложения; он же ключ наложения у глобуса.
    pub identifier: String,
    pub label: String,
    /// Вид поиска, из выдачи которого продукт взят: его жизнью наложение и
    /// живёт — уходит с продуктом из выдачи и с закрытием вкладки. `None` —
    /// продукт восстановлен по ключу (каталог, загрузки) и от выдач не
    /// зависит: снимает его только замена или «Снять с шара».
    pub source: Option<ViewId>,
    /// Четырёхугольник футпринта (UL, UR, LR, LL) — запасная привязка для
    /// продуктов без рамки UTM. Есть не у всех: сложный контур квадом не
    /// является, и такой продукт живёт только на рамке.
    pub quad: Option<[(f64, f64); 4]>,
    /// Ответ провайдера о растрах — в пути.
    pub imagery: veldsdk::Latest,
    /// Открытие растров ресурсами; появляется с ответом провайдера.
    pub assembly: Option<Assembly>,
    /// Наложение уехало глобусу (ресурсы уже во владении глобуса).
    pub sent: bool,
}

impl OverlayState {
    pub fn new(
        identifier: String,
        label: String,
        source: Option<ViewId>,
        quad: Option<[(f64, f64); 4]>,
    ) -> Self {
        Self {
            identifier,
            label,
            source,
            quad,
            imagery: veldsdk::Latest::default(),
            assembly: None,
            sent: false,
        }
    }
}

/// Сборка наложения: рамка от провайдера и открываемые растры.
pub struct Assembly {
    pub utm: Option<UtmFrame>,
    /// Сколько открытий ещё в пути. Ноль — собирать больше нечего.
    pub pending: usize,
    /// Открытые растры (роль → ресурс); владение у нас до передачи глобусу.
    pub collected: Vec<(i32, ResourceHandle)>,
}
