/// Вид предпросмотра. Показывает ровно один файл: второй снимок — это вторая
/// вкладка со своим состоянием, а не подмена содержимого здесь.
///
/// Превью идёт в два шага одной корреляцией: открыть ресурс (data-library или
/// data-provider) и отдать его image-loader. Тем же идентификатором заказчик
/// отменяет декодирование.
#[derive(Default)]
pub struct PreviewState {
    /// Текстура превью. Владелец — мы (image-loader передал владение),
    /// поэтому освобождаем её сами: при закрытии вкладки её уносит Drop.
    pub texture: Option<veldsdk::OwnedResource>,
    /// Открытый ресурс с файлом: наш, живёт только пока идёт декодирование.
    pub file: Option<veldsdk::OwnedResource>,
    pub current_path: String,
    /// Запрос на показ: актуален он или уже нет. Кому принадлежит ответ,
    /// отвечает таблица маршрутов модуля (`State::previews`) — вкладку могли
    /// закрыть, и тогда спрашивать здесь уже некого.
    pub request: veldsdk::Latest,
    pub error: Option<String>,
    /// Размеры исходного изображения и готового превью — их сообщает
    /// image-loader вместе с текстурой. Своего способа их узнать у нас нет:
    /// текстура превью уже уменьшена, а исходник мы не читали.
    pub source_size: Option<(u32, u32)>,
    pub preview_size: Option<(u32, u32)>,
    /// Масштаб показа: 0 — вписать в окно, иначе доля от натурального размера
    /// превью. Ноль отдельным значением, а не «1.0 и так вписано»: вписанный
    /// снимок меняет размер вместе с окном, а масштабированный — нет.
    pub zoom: f32,
}

impl PreviewState {
    pub fn is_loading(&self) -> bool {
        self.request.is_pending()
    }

    /// Заводит новый запрос: он становится актуальным, предыдущий — нет.
    pub fn begin(&mut self) -> String {
        self.request.begin()
    }

    /// Освобождает ресурс с файлом — после декодирования он не нужен.
    pub fn close_file(&mut self) {
        // Drop у OwnedResource освобождает регион.
        self.file = None;
    }

    /// Гасит вид: текстура больше не показывается и освобождается, запрос в
    /// полёте перестаёт быть актуальным. Учёт при этом не снимается — ресурс
    /// по нему ещё придёт, и освободит его обработчик ответа (см.
    /// handlers::preview), опознав по таблице маршрутов.
    ///
    /// Возвращает корреляцию брошенного запроса: ею вызывающий убивает
    /// декодирование, если оно уже идёт. Публикует он сам, своим стабом —
    /// состояние в шину не пишет, иначе исходящая связь модуля перестала бы
    /// быть видна в схеме.
    pub fn reset(&mut self) -> Option<String> {
        // Старая текстура больше не показывается и освобождается (Drop).
        self.texture = None;
        self.close_file();
        self.error = None;
        self.current_path.clear();
        self.source_size = None;
        self.preview_size = None;
        self.zoom = 0.0;

        self.request.abandon()
    }
}
