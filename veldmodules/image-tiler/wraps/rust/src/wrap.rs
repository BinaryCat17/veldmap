//! Публичный API image-tiler для модулей-потребителей: типы контракта,
//! арифметика пирамиды и механика работы с ней.

pub use super::proto::*;

// Механика потребителя: тайлы в видеопамяти и учёт того, что спрошено. Живёт
// здесь, а не у каждого потребителя своя: канва просмотра и наложения на шаре
// ведут один и тот же танец вокруг пирамиды и различаются только тем, какие
// ячейки им нужны прямо сейчас.
pub mod tiles;

// Единственный экземпляр правил пирамиды, общий с самим модулем: файл
// включается и сюда, и в crate::module (см. заголовок pyramid.rs). Потребитель
// считает уровни, сетки и краевые тайлы тем же кодом, которым тайлер их
// производит, — разойтись негде.
#[path = "../../../src/pyramid.rs"]
pub mod pyramid;

// Из чего сложен тайл кэша и по скольку их спрашивают — файл кэша, включённый
// и сюда (см. заголовок tile.rs): потолок запроса к кэшу и потолок аппетита
// потребителя обязаны быть одним числом, а не двумя.
#[path = "../../../../tile-cache/src/tile.rs"]
pub mod tile;
