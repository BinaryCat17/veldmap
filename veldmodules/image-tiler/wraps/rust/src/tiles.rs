    #[test]
    fn a_broken_pass_is_forgiven_once() {
        let cell = (0u32, 1u32, 1u32);
        let mut fetch = Fetch::default();

        fetch.produced(&[cell], true);
        assert!(fetch.hopeless(cell), "сорвавшуюся не просят сразу же");

        fetch.produced(&[], false);
        assert!(!fetch.hopeless(cell), "удачный проход снимает приговор");

        fetch.produced(&[cell], true);
        fetch.produced(&[], false);
        assert!(fetch.hopeless(cell), "второй срыв подряд — окончательный");

        // Смена источника забывает и приговор, и то, что заход уже давали.
        fetch.reset();
        assert!(!fetch.hopeless(cell));
    }

