    /// Ход добычи меряется заказом, а не тем, что видно: заказ переписывается
    /// только вместе с новым запросом, и камера его не двигает.
    #[test]
    fn ход_меряется_заказом() {
        let store = Store::new(1 << 30);
        let mut fetch = Fetch::default();
        assert_eq!(fetch.ordered(), (0, 0), "заказа ещё не было");

        let ask = fetch.ask(&store, "s", cells(0, 0..2, 0..2)).expect("запрос");
        assert_eq!(fetch.ordered(), (0, 4));
        fetch.arrived(ask[0]);
        assert_eq!(fetch.ordered(), (1, 4));
        // Сорвавшееся считается доведённым наравне с приездом: этих ячеек не
        // будет вовсе, и ждать их — значит не досчитать до конца никогда.
        fetch.produced(&ask[1..], true);
        assert_eq!(fetch.ordered(), (4, 4));
    }

    /// Промах, уехавший с глаз, в производство не идёт и с ожидания снимается —
    /// иначе он не спросится больше никогда. А заказ, закрытый кэшем целиком,
    /// называется своим исходом: по нему заказчик просит следующую ступень.
    #[test]
    fn промахи_отбираются_по_желанности() {
        let store = Store::new(1 << 30);
        let passes = passes();
        let mut fetch = Fetch::default();
        let ask = fetch.ask(&store, "s", cells(0, 0..3, 0..1)).expect("запрос");

        let produce = fetch.missed(&passes, "s", &"мы", true, &ask, ask.clone(), |addr| addr.1 == 0);
        assert!(matches!(produce, Missed::Produce(cells) if cells == vec![(0, 0, 0)]));
        // Чужой промах не наш: про него мы ничего не знаем.
        assert!(matches!(fetch.missed(&passes, "s", &"мы", true, &ask, [(0, 9, 9)], |_| true), Missed::Closed));

        let again = fetch.ask(&store, "s", cells(0, 0..3, 0..1)).expect("отсеянные вернулись");
        assert_eq!(again, vec![(0, 1, 0), (0, 2, 0)]);
    }

    /// Кэш отдал всё, о чём просили: промахов нет, ступень пройдена — и это
    /// отдельный исход, а не «нечего производить». Спутав их, заказчик не
    /// спросит следующую ступень и встанет до движения камеры.
    #[test]
