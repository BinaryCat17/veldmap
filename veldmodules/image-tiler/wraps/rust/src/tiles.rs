//! Тайлы пирамиды на стороне потребителя: что лежит в видеопамяти, чего
//! хотеть под нынешний взгляд и что из этого уже спрошено.
//!
//! Потребителей двое — канва просмотра и наложения на шаре, — и оба ведут один
//! и тот же танец: описать источник, выбрать уровень, спросить у кэша
//! недостающие ячейки, промахи отдать производителю, приехавшее сложить в
//! видеопамять и вытеснить оттуда давно не рисовавшееся. Различаются они
//! только тем, **какие ячейки видно прямо сейчас**: канве — прямоугольник её
//! камеры, наложению — то, что попало в кадр на шаре. Всё остальное —
//! механика, и держать её в двух экземплярах значит однажды починить промах в
//! одном месте и не починить в другом.
//!
//! Поэтому здесь ровно эта механика и ничего про протокол: [`Store`] — тайлы в
//! видеопамяти с бюджетом и вытеснением, [`want`] — какой уровень и какие
//! ячейки нужны, [`Fetch`] — учёт спрошенного по одному заказчику, [`Passes`] —
//! проходы производителя, по одному на источник. Сообщения кэшу и
//! производителю шлёт потребитель: топики объявлены в его схеме, и публиковать
//! за него нельзя (см. заголовок сгенерированного lib.rs) — сюда приезжает уже
//! готовый ответ.
//!
//! Место здесь по той же причине, что и у `pyramid`: правила пирамиды
//! принадлежат тому, кто её производит, и потребители работают с ней одним и
//! тем же кодом, а не каждый своим.

use std::collections::{HashMap, HashSet};

use veldsdk::graphics::{self as gfx, BindGroupId, TextureViewId};
use veldsdk::proto::core::ResourceHandle;

use super::pyramid;
use crate::proto::Reach;

/// Адрес тайла в пирамиде: уровень, колонка, ряд. Тот же, каким его знают
/// дисковый кэш и производитель.
pub type Addr = (u32, u32, u32);

/// Байт в текстуре одного тайла — ими и меряется бюджет видеопамяти. Считается
/// здесь, а не у каждого потребителя своей константой: бюджет и потолок
/// аппетита обязаны мерить одним.
const TILE_BYTES: u64 = (pyramid::TILE as u64) * (pyramid::TILE as u64) * 4;

/// Бюджет видеопамяти под тайлы по умолчанию, МиБ. Один на обоих
/// потребителей: хранилища у них разные (у каждого модуля своя линейная память
/// и свои bind group), а величина — одна и та же цена показа, и разъехавшись,
/// она молча дала бы шару и канве разные пределы.
pub const DEFAULT_VRAM_BUDGET_MB: u64 = 256;

/// Как назвать цену прохода в логе. Здесь, а не у каждого потребителя своей
/// строкой: факт один, и разойдясь в его названии, два лога читались бы как
/// про разные вещи.
pub fn reach_note(reach: Reach) -> &'static str {
    match reach {
        Reach::Exact => "произвольный доступ",
        Reach::Pyramid => "проход строит пирамиду целиком",
        Reach::Coarser => "проход на каждую ступень",
    }
}

/// Ресурс освободить, если он приехал. Приехавшая текстура уже наша, чей бы
/// ответ её ни привёз, и не принять её значит потерять видеопамять до конца
/// процесса.
pub fn discard(texture: Option<ResourceHandle>) {
    if let Some(handle) = texture {
        veldsdk::resource::release(handle);
    }
}

// ── Описанный источник ─────────────────────────────────────────

/// Всё, что потребитель обязан знать о пирамиде, прежде чем просить у неё
/// ячейки. Ровно то же самое у обоих: чем источник является, не зависит от
/// того, кто на него смотрит.
pub struct Meta {
    pub fingerprint: String,
    pub width: u32,
    pub height: u32,
    pub levels: u32,
    /// Во что обходится лишняя ступень пирамиды у этого источника — по нему
    /// выбирается лестница к цели (см. [`want`]).
    pub reach: Reach,
    /// Предел детали источника: подробнее него целью не бывает.
    pub finest: u32,
}

impl Meta {
    /// Чем источник оказался — строкой для лога.
    pub fn note(&self) -> String {
        format!(
            "{}×{}, уровней {}, {}",
            self.width, self.height, self.levels, reach_note(self.reach)
        )
    }
}

/// Ответ производителя — в [`Meta`] либо в причину, по которой источник
/// непригоден.
///
/// Проверки здесь, а не у каждого потребителя своей копией: пирамиду они
/// считают одним кодом, и разойтись в том, какое описание считать годным,
/// значило бы считать её по разным правилам. А вот **как показать причину** —
/// дело потребителя: у канвы для неё есть место на экране, у наложения только
/// лог, и сводить эти два ответа в один здесь было бы решением за них.
pub fn describe(msg: &crate::proto::Described) -> Result<Meta, String> {
    if !msg.error.is_empty() {
        return Err(msg.error.clone());
    }
    if msg.width == 0 || msg.height == 0 || msg.levels == 0 {
        return Err("источник описан пустым".to_string());
    }
    // Арифметика ячеек считается общим pyramid.rs — потребитель и
    // производитель обязаны быть собраны под одну сторону тайла.
    if msg.tile != pyramid::TILE {
        return Err(format!(
            "сторона тайла {} у производителя против {} у потребителя",
            msg.tile,
            pyramid::TILE
        ));
    }
    // Отпечаток — ключ и в видеопамяти, и на диске. Пустой сложил бы под одним
    // ключом тайлы разных источников, а производитель его таким не отдаёт:
    // проверка на границе, где кончается его слово и начинается наш учёт.
    if msg.fingerprint.is_empty() {
        return Err("источник описан без отпечатка".to_string());
    }
    Ok(Meta {
        fingerprint: msg.fingerprint.clone(),
        width: msg.width,
        height: msg.height,
        levels: msg.levels,
        reach: msg.reach(),
        finest: msg.finest,
    })
}

// ── Видеопамять ────────────────────────────────────────────────

pub struct Stored {
    /// Держит текстуру живой; bind group и view — производные от неё.
    _texture: veldsdk::OwnedResource,
    _view: TextureViewId,
    pub bind: BindGroupId,
    pub width: u32,
    pub height: u32,
    bytes: u64,
    /// Логическое время последнего прикосновения: приезда, обращения из кадра
    /// либо обращения к потомку. Им и вытесняем (см.
    /// [`Store::evict_to_budget`]).
    stamp: u64,
}

/// Тайлы в видеопамяти, с вытеснением по бюджету.
///
/// Хранилище одно на модуль, а не на зрителя: две вкладки с одним снимком —
/// это один набор тайлов, и бюджет видеопамяти тоже один на всех. Ключ —
/// отпечаток источника и адрес в пирамиде: тот же, что у дискового кэша, потому
/// что это тот же самый тайл ярусом выше.
///
/// Вытеснение — забывание: тайл остаётся на диске у tile-cache и вернётся
/// оттуда за миллисекунды.
pub struct Store {
    /// Отпечаток источника → тайлы. Двухэтажная карта, чтобы не клонировать
    /// отпечаток в ключ каждого тайла.
    sources: HashMap<String, HashMap<Addr, Stored>>,
    budget: u64,
    bytes: u64,
    /// Логические часы: и приезд, и обращение из кадра двигают их одинаково.
    tick: u64,
    /// Растёт на каждом добавлении и вытеснении: кадр, собранный при другом
    /// поколении, устарел.
    pub generation: u64,
}

impl Store {
    pub fn new(budget: u64) -> Self {
        Self { sources: HashMap::new(), budget, bytes: 0, tick: 0, generation: 0 }
    }

    /// Пустое хранилище с тем же бюджетом — на пересборку устройства: bind
    /// group'ы собраны под layout прежнего и с новым несовместимы.
    pub fn new_like(other: &Store) -> Self {
        Self::new(other.budget)
    }

    /// Потолок аппетита: сколько ячеек позволено хотеть одной пирамиде, чтобы
    /// её приезды не вытесняли нарисованное соседями.
    ///
    /// Половина бюджета делится между всеми, кто сейчас рисует, — а не каждому
    /// по половине: иначе шесть слоёв, каждый со своей половиной, вымывали бы
    /// друг друга по кругу, и не дорисовался бы ни один. Вторая половина
    /// остаётся предкам: ячейка рисуется ближайшим имеющимся предком, и его
    /// тайлы обязаны пережить приход своей ступени.
    ///
    /// Делится он между пирамидами, поэтому берёт отпечатки, а не их число:
    /// две вкладки с одним снимком — это один набор тайлов и одна доля бюджета,
    /// и свести повторы обязан тот, кто бюджетом и распоряжается.
    ///
    /// Меряется потолком видимое, а не уровень целиком, и в этом вся разница:
    /// гранула 10 000² нулевым уровнем не помещается ни в какой бюджет, и мерь
    /// мы им — снимок не показал бы подробностей ни на каком приближении, а
    /// видно от силы десяток ячеек, сколько ни приближай (см. [`want`]).
    pub fn cap_tiles<'a>(&self, drawing: impl IntoIterator<Item = &'a str>) -> u64 {
        let pyramids: HashSet<&str> = drawing.into_iter().collect();
        (self.budget / TILE_BYTES.max(1) / (2 * pyramids.len().max(1) as u64)).max(1)
    }

    /// [`Self::accept`], но ответом «лёг или нет»: не легший тайл — промах, а
    /// не ошибка ячейки, и вызывающему нужен именно этот один бит, чтобы снять
    /// ячейку с ожиданий верной стороной (см. [`Fetch::rejected`]).
    ///
    /// Причина не легшего уезжает в лог здесь: она одна и та же у обоих
    /// потребителей, и складывать её двумя строками значило бы читать один
    /// сбой как два разных.
    pub fn land(
        &mut self,
        fingerprint: &str,
        addr: Addr,
        texture: Option<ResourceHandle>,
        width: u32,
        height: u32,
        bind: impl FnOnce(&TextureViewId) -> veldsdk::anyhow::Result<BindGroupId>,
    ) -> bool {
        match self.accept(fingerprint, addr, texture, width, height, bind) {
            Ok(()) => true,
            Err(error) => {
                veldsdk::log::warn!(target: "tiles",
                    "тайл {}:{}:{} не принят: {}", addr.0, addr.1, addr.2, error);
                false
            }
        }
    }

    /// Принять приехавший тайл во владение: view создаётся здесь, а bind
    /// group — тем, кто его потом рисует: layout привязки принадлежит его
    /// пайплайну.
    ///
    /// Разбирает ответ целиком, включая негодный: пустая текстура, нулевые
    /// размеры и отказ графики освобождают приехавшее прямо здесь. Текстура
    /// уже наша, чей бы ответ её ни привёз, и вернуть её наверх «на всякий
    /// случай» значит завести второе место, где о ней надо помнить.
    pub fn accept(
        &mut self,
        fingerprint: &str,
        addr: Addr,
        texture: Option<ResourceHandle>,
        width: u32,
        height: u32,
        bind: impl FnOnce(&TextureViewId) -> veldsdk::anyhow::Result<BindGroupId>,
    ) -> Result<(), String> {
        let Some(texture) = texture else {
            return Err("в ответе нет текстуры".to_string());
        };
        if width == 0 || height == 0 {
            discard(Some(texture));
            return Err(format!("тайл {}×{}", width, height));
        }
        let texture = veldsdk::OwnedResource::new(texture);
        let view = gfx::create_texture_view(texture.id()).map_err(|e| e.to_string())?;
        let bind = bind(&view).map_err(|e| e.to_string())?;

        let bytes = u64::from(width) * u64::from(height) * 4;
        self.tick += 1;
        let tiles = self.sources.entry(fingerprint.to_string()).or_default();
        // Повтор (кэш и производитель могли прислать один тайл наперегонки)
        // замещается: старая текстура освобождается своим Drop.
        let stored = Stored {
            _texture: texture,
            _view: view,
            bind,
            width,
            height,
            bytes,
            stamp: self.tick,
        };
        if let Some(old) = tiles.insert(addr, stored) {
            self.bytes -= old.bytes;
        }
        self.bytes += bytes;
        self.generation += 1;
        self.evict_to_budget();
        Ok(())
    }

    /// Носитель ячейки: точный тайл, а пока его нет — ближайший имеющийся
    /// предок. Обращение продлевает жизнь в бюджете всей ветке.
    ///
    /// Одна ячейка — один носитель, поэтому перекрытий не бывает и буфер
    /// глубины не нужен. Адресация пирамиды это позволяет: тайл уровня z+1
    /// накрывает четыре тайла уровня z, и его четверть — ровно то усреднение,
    /// которое дал бы точный тайл (см. `pyramid::cell_uv`). Правило одно на
    /// обоих потребителей: написанное дважды, оно однажды разошлось бы.
    ///
    /// **Ветке, а не носителю.** Предок — это то, чем ячейку нарисуют, когда её
    /// точный тайл уедет из бюджета, и та же ступень, с которой пирамида
    /// набирается заново. Продлевай мы жизнь одному носителю, предки старились
    /// бы ровно с той минуты, когда их ступень достроилась: их никто не трогает,
    /// пока лист на месте. Вытесненные, они превращают любую панораму в подъём
    /// от вершины — снимок мутнеет на глазах и добирается ступенька за
    /// ступенькой, хотя ни один лист не понадобился заново.
    pub fn carrier(&mut self, fingerprint: &str, cell: Addr, levels: u32) -> Option<(Addr, &Stored)> {
        let addr = chain(cell, levels).find(|addr| self.contains(fingerprint, *addr))?;

        self.tick += 1;
        let tick = self.tick;
        let tiles = self.sources.get_mut(fingerprint)?;
        for addr in chain(cell, levels) {
            if let Some(stored) = tiles.get_mut(&addr) {
                stored.stamp = tick;
            }
        }
        Some((addr, tiles.get(&addr)?))
    }

    pub fn contains(&self, fingerprint: &str, addr: Addr) -> bool {
        self.sources.get(fingerprint).is_some_and(|tiles| tiles.contains_key(&addr))
    }

    /// Забыть источник целиком — его больше не показывают, и тайлам не с чего
    /// рисоваться.
    pub fn forget(&mut self, fingerprint: &str) {
        if let Some(tiles) = self.sources.remove(fingerprint) {
            for stored in tiles.values() {
                self.bytes -= stored.bytes;
            }
            self.generation += 1;
        }
    }

    /// Вон, пока не влезем: дольше всех не тронутое.
    ///
    /// Тронутое — это и приезд, и обращение из кадра, и обращение к потомку
    /// ([`Store::carrier`]): всё это разные способы сказать «тайл в работе», и
    /// мерка у них одна.
    ///
    /// **Приезд считается прикосновением**, хотя в кадре приехавший ещё не был
    /// и поставить его впереди нарисованного выглядит осторожным. Дело в том,
    /// что «нарисован» не стареет: напанорамировав десяток экранов, хранилище
    /// набивается тайлами, которые нарисованы когда-то и не нужны никому, — и в
    /// очереди на вытеснение они все стоят позади приезжающих. Полное такими
    /// хранилище перестаёт принимать что-либо вовсе: приехавший тайл оказывается
    /// единственным «невиданным» и вытесняет сам себя, следующий — себя, и заказ
    /// не складывается никогда. Снаружи это ровно то, на что похоже: снимок
    /// стоит мутным, а сеть работает без остановки.
    ///
    /// Что нарисованному при этом ничего не грозит, обеспечивает не порядок
    /// вытеснения, а потолок аппетита ([`Store::cap_tiles`]): видимое вместе с
    /// заказом занимает меньше половины бюджета, а тронуто оно позже всего
    /// прочего.
    fn evict_to_budget(&mut self) {
        if self.bytes <= self.budget {
            return;
        }
        let over = self.bytes - self.budget;
        let doomed = victims(
            self.sources.iter().flat_map(|(key, tiles)| {
                tiles.iter().map(move |(addr, stored)| (key.as_str(), *addr, stored.stamp, stored.bytes))
            }),
            over,
        );

        for (key, addr) in doomed {
            let Some(tiles) = self.sources.get_mut(&key) else { continue };
            if let Some(old) = tiles.remove(&addr) {
                self.bytes -= old.bytes;
            }
            if tiles.is_empty() {
                self.sources.remove(&key);
            }
            self.generation += 1;
        }
    }
}

/// Кого вытеснить, чтобы освободить `over` байт: дольше всех не тронутых, пока
/// не наберётся.
///
/// Чистая функция — правило закреплено тестом, а не прогонами: настоящий тайл в
/// хранилище не завести, не создав текстуру, а её без хоста не бывает.
///
/// Сортировка честна: бюджет в четверть гигабайта — это порядка двух сотен
/// тайлов, и случается она только при переполнении.
fn victims<'a>(
    tiles: impl Iterator<Item = (&'a str, Addr, u64, u64)>,
    over: u64,
) -> Vec<(String, Addr)> {
    let mut all: Vec<(&str, Addr, u64, u64)> = tiles.collect();
    all.sort_by_key(|&(.., stamp, _)| stamp);

    let mut freed = 0;
    let mut doomed = Vec::new();
    for (key, addr, _, bytes) in all {
        if freed >= over {
            break;
        }
        freed += bytes;
        doomed.push((key.to_string(), addr));
    }
    doomed
}

/// Ячейка и все её предки в пирамиде, снизу вверх. Одну и ту же точку снимка
/// рисует любой из них: пока точного тайла нет, ячейку несёт ближайший
/// имеющийся предок (см. [`Store::carrier`]).
fn chain(cell: Addr, levels: u32) -> impl Iterator<Item = Addr> {
    let (level, x, y) = cell;
    let up = levels.saturating_sub(1).saturating_sub(level);
    (0..=up).map(move |d| (level + d, x >> d, y >> d))
}

// ── Чего хотеть под нынешний взгляд ────────────────────────────

/// Уровень, к которому идут, ступень к нему и её видимые ячейки.
///
/// Одним значением, потому что считаются они вместе и порознь смысла не имеют:
/// уровень выбирается как раз по тому, сколько его ячеек видно, а ход добычи
/// меряется тем, сколько ступеней лестницы уже позади.
pub struct Want {
    /// Ступень: её просят у кэша, ею же и рисуют.
    pub level: u32,
    /// Ячейки ступени, попавшие в кадр.
    pub cells: Vec<Addr>,
    /// Ступеней в лестнице к цели, считая её саму, и сколько их позади.
    ///
    /// Ими меряется ход добычи, и считаются они здесь, потому что здесь
    /// лестница и строится: у источника, которому ступень стоит целого прохода,
    /// их две на всю пирамиду (см. [`ladder`]), и делить путь на все уровни
    /// значило бы рисовать полосу по ступеням, которых нет.
    pub steps: u32,
    pub climbed: u32,
}

impl Want {
    /// Путь к цели не пройден: за этой ступенью пойдёт следующая, и пойдёт
    /// сама — без единого движения камеры.
    pub fn climbing(&self) -> bool {
        self.climbed + 1 < self.steps
    }
}

/// Работа по пирамиде ещё идёт — то, из чего потребитель делает «готовим…».
///
/// Фактов три, и ни один поодиночке на этот вопрос не отвечает: каждый
/// пропускает ровно то, что ловят двое других.
///
/// * **Ячейки в полёте** (`fetch`). Между «последний тайл ступени приехал» и
///   «оформлен заказ следующей» в полёте нет ничего, и признак, выведенный
///   из одного полёта, мигал бы на каждой ступени.
/// * **По источнику идёт проход** (`passes`). Чей угодно: свои ячейки он
///   добудет заодно, а пока он идёт, второго не будет — ждать всё равно его.
/// * **Путь к цели не пройден** (`want`). Ступень, набранная целиком из кэша,
///   не поднимает ни одного прохода и не держит ни одной ячейки в полёте, — а
///   следующая за ней пойдёт немедленно, и объявить в этот миг работу
///   конченой значит сказать «загрузка кончилась» посреди загрузки.
///
/// `want` пустой — считать не по чему (нет места, камеры или описания): о
/// пройденном пути тогда сказать нечего, и ответ держится на первых двух.
pub fn working<K: PartialEq>(
    fetch: &Fetch,
    passes: &Passes<K>,
    fingerprint: &str,
    want: Option<&Want>,
) -> bool {
    fetch.waiting() || passes.going(fingerprint) || want.is_some_and(Want::climbing)
}

/// Что нужно пирамиде прямо сейчас: цель, ступень к ней и её ячейки.
///
/// Ответ один на обоих спрашивающих — на запрос тайлов и на сборку кадра:
/// заказанный уровень обязан быть тем же, который рисуют, а видимость
/// ячейки — тем же, по чему её просили. Разойдясь, они дают либо заказ
/// невидимого, либо непоказ добытого.
///
/// `sharpest` — уровень под экранный пиксель, единственное, что потребители
/// считают по-своему: у канвы это масштаб камеры, у наложения — метры на
/// пиксель кадра. `visible` — их же ответ на «что из этого уровня видно».
/// `finest` — предел детали самого источника (`Described.finest`).
pub fn want(
    sharpest: u32,
    levels: u32,
    finest: u32,
    cap: u64,
    reach: Reach,
    store: &Store,
    fetch: &Fetch,
    fingerprint: &str,
    visible: impl Fn(u32) -> Vec<Addr>,
) -> Want {
    let top = levels.saturating_sub(1);

    // Целевой уровень: экранный пиксель, загрублённый до того, что имеет смысл
    // хотеть. Ограничений два, и оба здесь, потому что ответ у них один — какой
    // уровень стоит держать в видеопамяти. Предел детали источника: подробнее
    // него не отдадут, и хотеть такой уровень значит просить отказ. Потолок
    // аппетита: видимое обязано влезать в свою долю бюджета.
    let mut target = sharpest.clamp(finest.min(top), top);
    let mut cells = visible(target);
    while target < top && cells.len() as u64 > cap {
        target += 1;
        cells = visible(target);
    }

    let ladder = ladder(target, top, reach);
    let (climbed, cells) = rung(
        &ladder,
        |level| match level == target {
            // Целевой уже посчитан выше — считать его второй раз значит второй
            // раз проецировать все его ячейки.
            true => cells.clone(),
            false => visible(level),
        },
        // Ячейка ступень не держит, если она уже есть либо её не будет вовсе.
        // Без второго ступень встала бы на непроизводимой ячейке навсегда.
        |addr| store.contains(fingerprint, addr) || fetch.hopeless(addr),
    );
    Want {
        level: ladder[climbed],
        cells,
        steps: ladder.len() as u32,
        climbed: climbed as u32,
    }
}

/// Ступень добычи: первая сверху ступень лестницы, которой ещё не хватает, — её
/// место в лестнице и её ячейки. Хватает всех — значит дошли до цели, и это
/// последняя ступень.
///
/// Пирамида набирается сверху вниз, а не прыжком к целевому уровню. Вершина —
/// это один тайл из самой мелкой копии файла: он приезжает за секунду и
/// накрывает снимок целиком, тогда как целевой уровень из десятка тайлов по
/// мегабайту едет полминуты, и всё это время показывать было бы нечего. Каждая
/// добытая ступень к тому же становится предком для следующей
/// ([`Store::carrier`]), поэтому дыр между ступенями не бывает.
fn rung(
    ladder: &[u32],
    cells_at: impl Fn(u32) -> Vec<Addr>,
    ready: impl Fn(Addr) -> bool,
) -> (usize, Vec<Addr>) {
    let last = ladder.len() - 1;
    for (at, &level) in ladder.iter().enumerate().take(last) {
        let cells = cells_at(level);
        if cells.iter().any(|addr| !ready(*addr)) {
            return (at, cells);
        }
    }
    (last, cells_at(ladder[last]))
}

/// Лестница к цели: уровни, по которым имеет смысл ступать, от вершины к самой
/// цели. Целью она всегда и кончается — ступать дальше некуда, — поэтому пустой
/// не бывает.
///
/// Обычно в ней все уровни до единого: ступень стоит своих тайлов — точечного
/// чтения у источника с произвольным доступом либо попадания в кэш у того, чей
/// единственный проход построил всю пирамиду разом, — а показать грубое сразу
/// лучше, чем не показывать ничего.
///
/// Но у источника, чей проход строит только запрошенный уровень и грубее
/// ([`Reach::Coarser`] — JPEG, JPEG 2000: за подробным приходят заново),
/// каждая ступень стоит целого чтения файла, и лестница умножала бы эту цену на
/// число ступеней. Там их две: вершина, чтобы снимок появился, и сразу цель.
fn ladder(target: u32, top: u32, reach: Reach) -> Vec<u32> {
    let steps = match reach {
        Reach::Coarser => (target < top).then_some(top).into_iter().collect(),
        Reach::Pyramid | Reach::Exact => ((target + 1)..=top).rev().collect::<Vec<u32>>(),
    };
    steps.into_iter().chain([target]).collect()
}

// ── Что спрошено и что производится ────────────────────────────

/// Учёт по одному заказчику: что уже спрошено, чего не спрашивать и чем
/// меряется ход добычи.
///
/// Заказчик — это вкладка канвы или растр наложения. Идущий проход сюда не
/// входит: он принадлежит источнику, а не заказчику (см. [`Passes`]).
#[derive(Default)]
pub struct Fetch {
    /// Спрошенные и ещё не приехавшие: второй раз их не просят.
    inflight: HashSet<Addr>,
    /// Те из сорвавшихся, кому второй заход уже давали: их приговор
    /// окончателен (см. [`Fetch::produced`]).
    retried: HashSet<Addr>,
    /// Ячейки, которых не будет: проход, в который их отдали, сорвался.
    ///
    /// Ячейками, а не уровнем: сорваться проход может от чего угодно — битый
    /// чанк, не выделилась текстура, оборвалось чтение, — и уровень тут ни при
    /// чём. Уровень, которого источник не отдаст в принципе, отсекается раньше
    /// и не отказом, а его собственным пределом детали (`Described.finest`,
    /// см. [`want`]): просить и получать один и тот же отказ незачем.
    failed: HashSet<Addr>,
    /// Ячейки последнего оформленного заказа — того, что уехал в кэш. Ими
    /// меряется ход добычи, а не тем, что видно прямо сейчас: видимое есть
    /// функция камеры, и доля, выведенная из него, ездит взад-вперёд на каждом
    /// кадре жеста. Заказ переписывается, только когда действительно уходит
    /// новый запрос.
    ordered: Vec<Addr>,
}

impl Fetch {
    /// Заказ и сколько из него уже дошло — то, чем меряется ход добычи.
    /// Дошедшим считается всё, что перестало быть ожидаемым: приехавшее и то,
    /// в чём отказали.
    pub fn ordered(&self) -> (u32, u32) {
        let done = self.ordered.iter().filter(|addr| !self.inflight.contains(addr)).count();
        (done as u32, self.ordered.len() as u32)
    }

    /// Спрошено и ещё не приехало: кэш ищет, производитель читает — работа идёт.
    /// Пусто — либо всё нужное уже есть, либо просить нечего.
    pub fn waiting(&self) -> bool {
        !self.inflight.is_empty()
    }

    /// Ячейка, которой не будет: проход, в который её отдали, сорвался.
    /// Спрашивают об этом те, кто выбирает ступень: без этого она встала бы на
    /// непроизводимой ячейке навсегда.
    pub fn hopeless(&self, addr: Addr) -> bool {
        self.failed.contains(&addr)
    }

    /// Источник сменился или кончился: всё, что помнилось, было про прежний.
    /// Идущий проход снимает не это — он живёт своим учётом (см. [`Passes`]).
    pub fn reset(&mut self) {
        self.inflight.clear();
        self.failed.clear();
        self.retried.clear();
        self.ordered.clear();
    }

    /// Что спросить у кэша: желаемое без того, что уже лежит, уже спрошено или
    /// уже не произведётся. `None` — спрашивать нечего.
    ///
    /// Идущий проход тут ни при чём, и это не упущение: кэш дёшев и отвечает
    /// тем, что в нём есть. Заказчик, ждущий чужого прохода, вправе тем
    /// временем забрать из кэша готовые ступени — иначе он стоял бы пустым
    /// минуту, имея под рукой всё, что ему нужно. Свои же ячейки, отданные в
    /// производство, остаются ожидаемыми и вторично не спрашиваются.
    ///
    /// Спрошенное сразу считается ожидаемым: пересчёт идёт на каждое движение
    /// камеры, и без этого одна и та же ячейка уехала бы в кэш десяток раз.
    pub fn ask(
        &mut self,
        store: &Store,
        fingerprint: &str,
        desired: impl IntoIterator<Item = Addr>,
    ) -> Option<Vec<Addr>> {
        let cells: Vec<Addr> = desired
            .into_iter()
            .filter(|addr| {
                !store.contains(fingerprint, *addr)
                    && !self.inflight.contains(addr)
                    && !self.failed.contains(addr)
            })
            .collect();
        if cells.is_empty() {
            return None;
        }
        self.inflight.extend(cells.iter().copied());
        self.ordered = cells.clone();
        Some(cells)
    }

    /// Промахи кэша → что делать дальше. `still_wanted` отсеивает уехавшее с
    /// глаз, пока запрос шёл: его переспросят, когда оно вернётся в кадр, а
    /// производить его сейчас значит занять единственный проход не тем.
    ///
    /// Всё, что в производство не пошло, снимается с ожидания: иначе следующий
    /// пересчёт сочтёт эти ячейки уже спрошенными и не переспросит никогда.
    pub fn missed<K: PartialEq>(
        &mut self,
        passes: &Passes<K>,
        fingerprint: &str,
        asked: &[Addr],
        misses: impl IntoIterator<Item = Addr>,
        still_wanted: impl Fn(Addr) -> bool,
    ) -> Missed {
        let going = passes.going(fingerprint);
        let mut produce = Vec::new();
        for addr in misses {
            // Не из этого запроса — про него мы ничего не знаем.
            if !asked.contains(&addr) {
                continue;
            }
            if !going && still_wanted(addr) && !self.failed.contains(&addr) {
                produce.push(addr);
            } else {
                self.inflight.remove(&addr);
            }
        }
        match (produce.is_empty(), going) {
            (false, _) => Missed::Produce(produce),
            (true, true) => Missed::Waiting,
            (true, false) => Missed::Closed,
        }
    }

    /// Запрос кэша сорвался: ожидания снимаются, и на следующем пересчёте они
    /// спросятся заново.
    pub fn forget_asked(&mut self, cells: &[Addr]) {
        for addr in cells {
            self.inflight.remove(addr);
        }
    }

    /// Тайл приехал и лёг — из ожидания вон, чей бы запрос его ни привёз.
    pub fn arrived(&mut self, addr: Addr) {
        self.inflight.remove(&addr);
    }

    /// Ответ про ячейку пришёл, но тайл не лёг: не выделилась текстура, не
    /// собралась привязка, приехало не изображение. Больше её не просят.
    ///
    /// Не просто «снять с ожидания», потому что причина здесь не про попытку:
    /// тот же ответ приедет и в следующий раз. А переспрашивать её нельзя ещё
    /// и потому, что ступень тогда не сдвинется никогда — заказ будет
    /// закрываться кэшем, пересчёт спрашивать то же самое, и так по кругу.
    pub fn rejected(&mut self, addr: Addr) {
        self.inflight.remove(&addr);
        self.failed.insert(addr);
    }

    /// Проход кончился, чем бы он ни кончился. `failed` — сорвался: эти ячейки
    /// больше не просят, иначе каждый сдвиг камеры звал бы производителя за тем
    /// же отказом.
    ///
    /// Приговор при этом не вечный. Сорваться проход может от чего угодно —
    /// оборвалось чтение, не выделилась текстура, — и такой сбой проходит сам;
    /// а держись он до переоткрытия вкладки, в резком снимке оставалось бы
    /// мутное пятно, вылечить которое можно только случайно. Поэтому удачный
    /// проход по тому же источнику снимает приговор: сбой был у прохода, а не у
    /// ячейки. Второй раз подряд — уже свойство самой ячейки, и её оставляют;
    /// иначе безнадёжная ячейка переспрашивалась бы после каждого удачного
    /// прохода соседей.
    pub fn produced(&mut self, cells: &[Addr], failed: bool) {
        self.forget_asked(cells);
        match failed {
            true => self.failed.extend(cells.iter().copied()),
            false => self.forgive(),
        }
    }

    /// Простить тем, кому второго захода ещё не давали.
    fn forgive(&mut self) {
        let mut retried = std::mem::take(&mut self.retried);
        self.failed.retain(|addr| !retried.insert(*addr));
        self.retried = retried;
    }
}

/// Чем кончился разбор промахов кэша ([`Fetch::missed`]).
///
/// Названными исходами, а не пустым списком: пустота значила бы сразу две
/// разные вещи, и та, о которой забыли, останавливала бы добычу молча.
pub enum Missed {
    /// За этими ячейками — к производителю.
    Produce(Vec<Addr>),
    /// Идти некуда и ждать нечего: кэш закрыл заказ целиком либо остальное
    /// уехало с глаз. Ступень тем самым пройдена, и спросить следующую надо
    /// здесь же. Иначе цикл «ступень доехала → просим следующую» замыкается
    /// только через конец прохода производителя, которого не было, и добыча
    /// встаёт до ближайшего движения камеры: снаружи это выглядит как «стоит
    /// мутным, а потом от одного щелчка становится резким».
    Closed,
    /// По источнику идёт проход. Ждём молча: сложенное им ляжет в кэш, а его
    /// конец пересчитает нужное всем, кто на этот источник смотрит.
    Waiting,
}

/// Проходы производителя: по одному на источник.
///
/// Один — потому что проход читает файл, и второй по тому же файлу не вторая
/// работа, а та же самая заново. Учёт поэтому и не у заказчика: заказчиков у
/// источника бывает несколько — две вкладки с одним снимком, два слоя одного
/// продукта, — а проход у них общий. Знать о нём обязаны все, иначе каждый
/// шлёт свой запрос кэшу, получает те же промахи и упирается в ту же очередь.
///
/// `K` — чем потребитель называет своих заказчиков: у канвы это имя вкладки, у
/// глобуса — слой и роль растра. Помнить его обязательно, потому что **проход
/// живёт ровно столько, сколько ресурс, который он читает**. Отпечаток у
/// заказчиков общий, а ресурсы у каждого свои: файл открывают порознь, и грант
/// тайлеру живёт не дольше самого ресурса. Уходящий заказчик поэтому свой
/// проход уносит с собой — сберечь его «для соседа» значит оставить чтение над
/// освобождённым ресурсом, то есть выбросить минуту работы и приписать соседу
/// чужую ошибку.
///
/// Убийство и снятие с учёта разведены по разным ключам, и это не случайность.
/// Убивают проход по его заказчику — «этому файл больше не нужен»; снимают с
/// учёта по корреляции — «кончился именно тот проход». Снимай мы по источнику,
/// поздний конец убитого прохода сносил бы запись нового, уже начатого по тому
/// же файлу.
pub struct Passes<K> {
    by_source: HashMap<String, Pass<K>>,
}

struct Pass<K> {
    /// Корреляция запроса — ею же его и убивают.
    correlation: String,
    /// Уровень, ради которого проход затеян.
    level: u32,
    /// Кто его завёл.
    owner: K,
}

impl<K> Default for Passes<K> {
    fn default() -> Self {
        Self { by_source: HashMap::new() }
    }
}

impl<K: PartialEq> Passes<K> {
    /// По источнику идёт проход — спрашивать по нему нечего до его конца.
    pub fn going(&self, fingerprint: &str) -> bool {
        self.by_source.contains_key(fingerprint)
    }

    /// Проход начат.
    pub fn begin(&mut self, fingerprint: &str, owner: K, correlation: String, level: u32) {
        self.by_source.insert(fingerprint.to_string(), Pass { correlation, level, owner });
    }

    /// Проход, ставший бесполезным: он производит уровень **подробнее** того,
    /// который смотрят сейчас, — такими тайлами грубую ячейку не нарисовать.
    /// Отдаёт его корреляцию; убивает её вызывающий, у него для этого свой
    /// `cancel`.
    ///
    /// Проход грубее нужного не убивается, и это не поблажка: ячейка рисуется
    /// ближайшим имеющимся предком, то есть тайлом любого уровня выше, — а
    /// один щелчок колеса растянут инерцией на секунду и меняет уровень по
    /// нескольку раз. Убивая проход на каждой смене, мы выбрасывали бы
    /// наполовину прочитанный файл столько же раз за одно приближение.
    ///
    /// По той же причине снимает его только заведший. Проход общий, а уровень
    /// у заказчиков свой: соседняя вкладка того же снимка, отъехавшая на шаг,
    /// иначе выбрасывала бы чужое наполовину прочитанное чтение — и тут же
    /// заводила своё, которое так же выбросили бы в ответ.
    pub fn stale(&mut self, fingerprint: &str, owner: &K, level: u32) -> Option<String> {
        let stale = self
            .by_source
            .get(fingerprint)
            .is_some_and(|pass| &pass.owner == owner && pass.level < level);
        match stale {
            true => self.by_source.remove(fingerprint).map(|pass| pass.correlation),
            false => None,
        }
    }

    /// Заказчик уходит — со снимка, из вкладки, с шара: отдаёт корреляцию его
    /// прохода, если тот идёт. Убивает её вызывающий, у него для этого свой
    /// `cancel`.
    ///
    /// Чужой проход не трогается, и ждать от этого нечего: сосед читает свой
    /// ресурс, который никуда не делся. А вот свой уносится обязательно —
    /// ресурс под ним сейчас освободят (см. заголовок [`Passes`]).
    pub fn abandon(&mut self, fingerprint: &str, owner: &K) -> Option<String> {
        let ours = self.by_source.get(fingerprint).is_some_and(|pass| &pass.owner == owner);
        match ours {
            true => self.by_source.remove(fingerprint).map(|pass| pass.correlation),
            false => None,
        }
    }

    /// Проход кончился, чем бы он ни кончился. По корреляции, а не по
    /// источнику: заказчика могли закрыть, а проход по тому же файлу успеть
    /// начать заново.
    pub fn finish(&mut self, correlation: &str) {
        self.by_source.retain(|_, pass| pass.correlation != correlation);
    }
}

