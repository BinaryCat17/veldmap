/// Уровень, к которому идут, ступень к нему и её видимые ячейки.
///
/// Одним значением, потому что считаются они вместе и порознь смысла не имеют:
/// уровень выбирается как раз по тому, сколько его ячеек видно, а ход добычи
/// меряется тем, сколько ступеней лестницы уже позади.
pub struct Want {
    /// Ступень: её просят у кэша, ею же и рисуют.
    pub level: u32,
    /// Уровень, ради которого лестница и строится: экранный пиксель,
    /// загрублённый до того, что имеет смысл хотеть, — по пределу детали
    /// источника и по потолку ячеек в видеопамяти.
    ///
    /// Отдельно от ступени, потому что смотрят цель, а ступень — способ до
    /// неё дойти: по ней нельзя судить, устарел ли идущий проход (см.
    /// [`Passes::stale`]).
    pub target: u32,
    /// Ячейки ступени, попавшие в кадр.
    pub cells: Vec<Addr>,
    /// Ступеней в лестнице к цели, считая её саму, и сколько их позади.
    ///
    /// Ими меряется ход добычи, и считаются они здесь, потому что здесь
    /// лестница и строится: у источника, которому ступень стоит целого прохода,
    /// их две на всю пирамиду (см. [`ladder`]), и делить путь на все уровни
    /// значило бы рисовать полосу по ступеням, которых нет.
    pub steps: u32,
    pub climbed: u32,
}

impl Want {
    /// Путь к цели не пройден: за этой ступенью пойдёт следующая, и пойдёт
    /// сама — без единого движения камеры.
    pub(crate) fn climbing(&self) -> bool {
        self.climbed + 1 < self.steps
    }
}

/// Работа по пирамиде ещё идёт — то, из чего потребитель делает «готовим…».
///
/// Фактов три, и ни один поодиночке на этот вопрос не отвечает: каждый
/// пропускает ровно то, что ловят двое других.
///
/// * **Ячейки в полёте** (`fetch`). Между «последний тайл ступени приехал» и
///   «оформлен заказ следующей» в полёте нет ничего, и признак, выведенный
///   из одного полёта, мигал бы на каждой ступени.
/// * **По источнику идёт проход** (`passes`). Чей угодно: свои ячейки он
///   добудет заодно, а пока он идёт, второго не будет — ждать всё равно его.
/// * **Путь к цели не пройден** (`want`). Ступень, набранная целиком из кэша,
///   не поднимает ни одного прохода и не держит ни одной ячейки в полёте, — а
///   следующая за ней пойдёт немедленно, и объявить в этот миг работу
///   конченой значит сказать «загрузка кончилась» посреди загрузки.
///
/// `want` пустой — считать не по чему (нет места, камеры или описания): о
/// пройденном пути тогда сказать нечего, и ответ держится на первых двух.
pub fn working<K: PartialEq>(
    fetch: &Fetch,
    passes: &Passes<K>,
    fingerprint: &str,
    want: Option<&Want>,
) -> bool {
    fetch.waiting() || passes.going(fingerprint) || want.is_some_and(Want::climbing)
}

/// Ход внутри ступени: чем двигать полосу и что о нём позволено сказать вслух.
///
/// Один ответ на обоих потребителей пирамиды, потому что вопрос у них один, а
/// правило годности байт — не про показ, а про источник: сложенное у каждого
/// своё, оно разошлось бы ровно там, где разойтись всего заметнее — в числах на
/// экране против длины полосы под ними.
#[derive(Clone, Copy, PartialEq, Default)]
pub struct Inside {
    /// Доля ступени, 0..1.
    pub share: f64,
    /// Прочитано байт источника из скольки — ровно то, что позволено показать.
    /// Нулевой знаменатель значит «мерить нечем», а не «ноль байт».
    pub read: (u64, u64),
}

/// Этот уровень читается точечно — ровно заказанными кусками, а не проходом по
/// файлу.
///
/// Одно понятие на три вопроса, и спрашивается оно про уровень, а не про род
/// источника. Родом ответить нельзя: у одного и того же полосного файла
/// подробный уровень идёт окном, а грубый — проходом, и что бы про него ни
/// сказать целиком, для одной из половин это будет неправдой.
///
/// Три вопроса такие, и все они про то, что отдаёт проход:
/// * годны ли его байты как мерка хода ([`readable`]) — у точечного чтения
///   счётчик прочитанного водяной знак головы, а не объём;
/// * откладывать ли промахи до его конца ([`Fetch::missed`]) — точечный кладёт
///   в кэш только заказанное, проход кладёт всю пирамиду;
/// * можно ли снять проход, ушедший из поля зрения ([`Pass::abandoned_by`]) —
///   уехавшее место проход добудет заодно, а точечное чтение нет.
pub fn pointwise(meta: &Meta, level: u32) -> bool {
    level < meta.windowed
}

/// Считать ли байты прохода правдой о ходе.
///
/// Отказов два, и оба про источник, а не про показ.
///
/// * Точечное чтение — счётчик прочитанного там водяной знак головы чтения
///   (`Metered` у тайлера), и при произвольном доступе он прыгает к концу файла
///   с первого же окна: доля вышла бы почти единицей на пустом месте.
/// * Прочитано во весь размер — так отвечает источник, который разбор читает
///   целиком (NetCDF): байты сравнялись со знаменателем ещё до прохода, и
///   дальше идёт декодирование, о котором они не говорят ничего. Взятые за
///   долю, они держали бы полосу полной всю минуту работы.
fn readable(pass: (u64, u64), pointwise: bool) -> bool {
    let (read, total) = pass;
    total > 0 && read < total && !pointwise
}

/// Ход внутри ступени по заказу и по байтам идущего прохода.
///
/// По большему из двух: ступень бывает в один тайл, а чтобы его отдать,
/// последовательный источник читается целиком — по ячейкам всё это время
/// сделано ровно ноль, и сказать о работе больше нечем. Пустой заказ значит
/// «спрашивать было нечего»: ступень закрыта, и считать её недобранной было бы
/// неправдой.
pub fn inside(ordered: (u32, u32), pass: (u64, u64), pointwise: bool) -> Inside {
    let read = match readable(pass, pointwise) {
        true => pass,
        false => (0, 0),
    };
    let by_bytes = match read {
        (_, 0) => 0.0,
        (read, total) => (read as f64 / total as f64).clamp(0.0, 1.0),
    };
    let share = match ordered.1 {
        0 => 1.0,
        total => (f64::from(ordered.0) / f64::from(total)).max(by_bytes).clamp(0.0, 1.0),
    };
    Inside { share, read }
}

/// Что нужно пирамиде прямо сейчас: цель, ступень к ней и её ячейки.
///
/// Ответ один на обоих спрашивающих — на запрос тайлов и на сборку кадра:
/// заказанный уровень обязан быть тем же, который рисуют, а видимость
/// ячейки — тем же, по чему её просили. Разойдясь, они дают либо заказ
/// невидимого, либо непоказ добытого.
///
/// `sharpest` — уровень под экранный пиксель, единственное, что потребители
/// считают по-своему: у канвы это масштаб камеры, у наложения — метры на
/// пиксель кадра. `visible` — их же ответ на «что из этого уровня видно».
/// `finest` — предел детали самого источника (`Described.finest`).
pub fn want(
    sharpest: u32,
    levels: u32,
    finest: u32,
    cap: u64,
    reach: Reach,
    store: &Store,
    fetch: &Fetch,
    fingerprint: &str,
    visible: impl Fn(u32) -> Vec<Addr>,
) -> Want {
    let top = levels.saturating_sub(1);

    // Целевой уровень: экранный пиксель, загрублённый до того, что имеет смысл
    // хотеть. Ограничений два, и оба здесь, потому что ответ у них один — какой
    // уровень стоит держать в видеопамяти. Предел детали источника: подробнее
    // него не отдадут, и хотеть такой уровень значит просить отказ. Потолок
    // аппетита: видимое обязано влезать в свою долю бюджета.
    let mut target = sharpest.clamp(finest.min(top), top);
    let mut cells = visible(target);
    while target < top && cells.len() as u64 > cap {
        target += 1;
        cells = visible(target);
    }

    let ladder = ladder(target, top, reach);
    let (climbed, cells) = rung(
        &ladder,
        |level| match level == target {
            // Целевой уже посчитан выше — считать его второй раз значит второй
            // раз проецировать все его ячейки.
            true => cells.clone(),
            false => visible(level),
        },
        // Ячейка ступень не держит, если она уже есть либо её не будет вовсе.
        // Без второго ступень встала бы на непроизводимой ячейке навсегда.
        |addr| store.contains(fingerprint, addr) || fetch.hopeless(addr),
    );
    Want {
        level: ladder[climbed],
        target,
        cells,
        steps: ladder.len() as u32,
        climbed: climbed as u32,
    }
}

/// Ступень добычи: первая сверху ступень лестницы, которой ещё не хватает, — её
/// место в лестнице и её ячейки. Хватает всех — значит дошли до цели, и это
/// последняя ступень.
///
/// Пирамида набирается сверху вниз, а не прыжком к целевому уровню. Вершина —
/// это один тайл из самой мелкой копии файла: он приезжает за секунду и
/// накрывает снимок целиком, тогда как целевой уровень из десятка тайлов по
/// мегабайту едет полминуты, и всё это время показывать было бы нечего. Каждая
/// добытая ступень к тому же становится предком для следующей
/// ([`Store::carrier`]), поэтому дыр между ступенями не бывает.
fn rung(
    ladder: &[u32],
    cells_at: impl Fn(u32) -> Vec<Addr>,
    ready: impl Fn(Addr) -> bool,
) -> (usize, Vec<Addr>) {
    let last = ladder.len() - 1;
    for (at, &level) in ladder.iter().enumerate().take(last) {
        let cells = cells_at(level);
        if cells.iter().any(|addr| !ready(*addr)) {
            return (at, cells);
        }
    }
    (last, cells_at(ladder[last]))
}

/// Лестница к цели: уровни, по которым имеет смысл ступать, от вершины к самой
/// цели. Целью она всегда и кончается — ступать дальше некуда, — поэтому пустой
/// не бывает.
///
/// Обычно в ней все уровни до единого: ступень стоит своих тайлов — точечного
/// чтения у источника с произвольным доступом либо попадания в кэш у того, чей
/// единственный проход построил всю пирамиду разом, — а показать грубое сразу
/// лучше, чем не показывать ничего.
///
/// Но у источника, чей проход строит только запрошенный уровень и грубее
/// ([`Reach::Coarser`] — JPEG, JPEG 2000: за подробным приходят заново),
/// каждая ступень стоит целого чтения файла, и лестница умножала бы эту цену на
/// число ступеней. Там их две: вершина, чтобы снимок появился, и сразу цель.
fn ladder(target: u32, top: u32, reach: Reach) -> Vec<u32> {
    let steps = match reach {
        Reach::Coarser => (target < top).then_some(top).into_iter().collect(),
        // Окно: промежуточных ступеней нет ни одной — лестница из одной цели
        // (её дописывает `chain` ниже). Всякая ступень грубее цели стои́т у
        // такого источника целого файла, то есть дороже самой цели, и «показать
        // грубое сразу» обернулось бы «показать поздно и дорого». Грубый край
        // закрывает соседний растр (у Sentinel-1 квиклук), а нет соседа — сама
        // цель, взятая проходом.
        Reach::Windowed => Vec::new(),
        Reach::Pyramid | Reach::Exact => ((target + 1)..=top).rev().collect::<Vec<u32>>(),
    };
    steps.into_iter().chain([target]).collect()
}

// ── Что спрошено и что производится ────────────────────────────

/// Учёт по одному заказчику: что уже спрошено, чего не спрашивать и чем
/// меряется ход добычи.
///
/// Заказчик — это вкладка канвы или растр наложения. Идущий проход сюда не
/// входит: он принадлежит источнику, а не заказчику (см. [`Passes`]).
#[derive(Default)]
pub struct Fetch {
    /// Спрошенные и ещё не приехавшие: второй раз их не просят.
    inflight: HashSet<Addr>,
    /// Те из сорвавшихся, кому второй заход уже давали: их приговор
    /// окончателен (см. [`Fetch::produced`]).
    retried: HashSet<Addr>,
    /// Ячейки, которых не будет: проход, в который их отдали, сорвался.
    ///
    /// Ячейками, а не уровнем: сорваться проход может от чего угодно — битый
    /// чанк, не выделилась текстура, оборвалось чтение, — и уровень тут ни при
    /// чём. Уровень, которого источник не отдаст в принципе, отсекается раньше
    /// и не отказом, а его собственным пределом детали (`Described.finest`,
    /// см. [`want`]): просить и получать один и тот же отказ незачем.
    failed: HashSet<Addr>,
    /// Ячейки последнего оформленного заказа — того, что уехал в кэш. Ими
    /// меряется ход добычи, а не тем, что видно прямо сейчас: видимое есть
    /// функция камеры, и доля, выведенная из него, ездит взад-вперёд на каждом
    /// кадре жеста. Заказ переписывается, только когда действительно уходит
    /// новый запрос.
    ordered: Vec<Addr>,
    /// Промахи, отложенные до конца собственного прохода: спрашивать по
    /// источнику всё равно нечего, пока он идёт, а сняв их с ожидания, мы
    /// спрашивали бы кэш о них на каждом кадре заново.
    ///
    /// Отдельным множеством, а не признаком у ячейки: снимаются они все разом
    /// и по чужому поводу — концу прохода, — и без списка пришлось бы искать
    /// их перебором всего ожидаемого.
    deferred: HashSet<Addr>,
    /// Ячейки, на которых мы уже спотыкались: вторая осечка подряд на одной и
    /// той же — уже её свойство, а не наша (см. [`Fetch::stumbled`]).
    stumbled: HashSet<Addr>,
}

impl Fetch {
    /// Заказ и сколько из него уже дошло — то, чем меряется ход добычи.
    /// Дошедшим считается всё, что перестало быть ожидаемым: приехавшее и то,
    /// в чём отказали.
    pub fn ordered(&self) -> (u32, u32) {
        let done = self.ordered.iter().filter(|addr| !self.inflight.contains(addr)).count();
        (done as u32, self.ordered.len() as u32)
    }

    /// Спрошено и ещё не приехало: кэш ищет, производитель читает — работа идёт.
    /// Пусто — либо всё нужное уже есть, либо просить нечего.
    pub(crate) fn waiting(&self) -> bool {
        !self.inflight.is_empty()
    }

    /// Эта ячейка едет прямо сейчас — то, чем показ метит грузящееся место на
    /// картинке.
    ///
    /// Два живых ограничения, и оба нужны смотрящему. Отложенные за своим
    /// проходом из ожидания не выпадают ([`Fetch::missed`]), поэтому признак
    /// накрывает самое долгое, что бывает с ячейкой, — молчаливое чтение
    /// последовательного источника; а при чужом проходе ячейка с ожидания
    /// снимается, и работа тогда видна только слоевым [`working`].
    ///
    /// Приговорённые ячейки спрашивать не нужно: с ожидания их снимают тем же
    /// движением, каким выносят приговор ([`Fetch::rejected`],
    /// [`Fetch::produced`]), — иначе безнадёжная ячейка светилась бы вечно.
    pub fn coming(&self, addr: Addr) -> bool {
        self.inflight.contains(&addr)
    }

    /// Ячейка, которой не будет: проход, в который её отдали, сорвался.
    /// Спрашивают об этом те, кто выбирает ступень: без этого она встала бы на
    /// непроизводимой ячейке навсегда.
    pub(crate) fn hopeless(&self, addr: Addr) -> bool {
        self.failed.contains(&addr)
    }

    /// Источник сменился или кончился: всё, что помнилось, было про прежний.
    /// Идущий проход снимает не это — он живёт своим учётом (см. [`Passes`]).
    pub fn reset(&mut self) {
        self.inflight.clear();
        self.failed.clear();
        self.retried.clear();
        self.ordered.clear();
        self.deferred.clear();
        self.stumbled.clear();
    }

    /// По источнику никто не идёт — отложенному больше нечего ждать.
    ///
    /// Спрашивают об этом там же, где выбирают ступень, и это единственная
    /// точка отпускания: конец прохода для неё не годится. Конец приходит по
    /// корреляции, а `Fetch` корреляций не знает — запоздавший конец прежнего
    /// прохода отпустил бы откладывания нового, и штурм кэша вернулся бы до
    /// конца этого нового.
    pub fn resume(&mut self) {
        for addr in std::mem::take(&mut self.deferred) {
            self.inflight.remove(&addr);
        }
    }

    /// Что спросить у кэша: желаемое без того, что уже лежит, уже спрошено или
    /// уже не произведётся. `None` — спрашивать нечего.
    ///
    /// Идущий проход тут ни при чём, и это не упущение: кэш дёшев и отвечает
    /// тем, что в нём есть. Заказчик, ждущий чужого прохода, вправе тем
    /// временем забрать из кэша готовые ступени — иначе он стоял бы пустым
    /// минуту, имея под рукой всё, что ему нужно. Свои же ячейки, отданные в
    /// производство, остаются ожидаемыми и вторично не спрашиваются.
    ///
    /// Спрошенное сразу считается ожидаемым: пересчёт идёт на каждое движение
    /// камеры, и без этого одна и та же ячейка уехала бы в кэш десяток раз.
    pub fn ask(
        &mut self,
        store: &Store,
        fingerprint: &str,
        desired: impl IntoIterator<Item = Addr>,
    ) -> Option<Vec<Addr>> {
        let cells: Vec<Addr> = desired
            .into_iter()
            .filter(|addr| {
                !store.contains(fingerprint, *addr)
                    && !self.inflight.contains(addr)
                    && !self.failed.contains(addr)
            })
            .collect();
        if cells.is_empty() {
            return None;
        }
        self.inflight.extend(cells.iter().copied());
        self.ordered = cells.clone();
        Some(cells)
    }

    /// Промахи кэша → что делать дальше. `still_wanted` отсеивает уехавшее с
    /// глаз, пока запрос шёл: его переспросят, когда оно вернётся в кадр, а
    /// производить его сейчас значит занять единственный проход не тем.
    ///
    /// Всё, что в производство не пошло, снимается с ожидания: иначе следующий
    /// пересчёт сочтёт эти ячейки уже спрошенными и не переспросит никогда.
    ///
    /// Кроме одного случая: пока идёт **наш** проход, отдающий ровно
    /// заказанное ([`pointwise`]), переспрашивать нечего —
    /// нового в кэше не появится, а пересчёт желаемого идёт на каждом кадре,
    /// и снятая ячейка уходила бы туда сотнями запросов об одном и том же.
    /// Такие откладываются, пока проход идёт, и отпускает их
    /// [`Fetch::resume`] — по отсутствию прохода, а не по его концу.
    ///
    /// У прочих источников проход кладёт в кэш больше, чем отдаёт заказчику:
    /// пирамиду целиком либо ступень и всё грубее неё. А узнать, что тайл
    /// лёг, можно только спросив — о своих пополнениях кэш не сообщает. Там
    /// переспрашивание не холостое: это единственный способ увидеть
    /// обнажившийся край раньше конца прохода.
    ///
    /// Чужой проход не откладывают никогда: его конец наших ожиданий не
    /// снимет, и отложенное по нему зависло бы навсегда.
    pub fn missed<K: PartialEq>(
        &mut self,
        passes: &Passes<K>,
        fingerprint: &str,
        owner: &K,
        pointwise: bool,
        asked: &[Addr],
        misses: impl IntoIterator<Item = Addr>,
        still_wanted: impl Fn(Addr) -> bool,
    ) -> Missed {
        let going = passes.going(fingerprint);
        let ours = passes.mine(fingerprint, owner) && pointwise;
        let mut produce = Vec::new();
        for addr in misses {
            // Не из этого запроса — про него мы ничего не знаем.
            if !asked.contains(&addr) {
                continue;
            }
            if !going && still_wanted(addr) && !self.failed.contains(&addr) {
                produce.push(addr);
            } else if ours {
                self.deferred.insert(addr);
            } else {
                self.inflight.remove(&addr);
            }
        }
        match (produce.is_empty(), going) {
            (false, _) => Missed::Produce(produce),
            (true, true) => Missed::Waiting,
            (true, false) => Missed::Closed,
        }
    }

    /// Запрос кэша сорвался: ожидания снимаются, и на следующем пересчёте они
    /// спросятся заново.
    pub fn forget_asked(&mut self, cells: &[Addr]) {
        for addr in cells {
            self.inflight.remove(addr);
        }
    }

    /// Тайл приехал и лёг — из ожидания вон, чей бы запрос его ни привёз.
    pub fn arrived(&mut self, addr: Addr) {
        self.inflight.remove(&addr);
        // Удача и делает счёт осечек счётом подряд (см. [`Fetch::stumbled`]).
        self.stumbled.remove(&addr);
    }

    /// Ответ про ячейку пришёл, но тайл не лёг: не выделилась текстура, не
    /// собралась привязка, приехало не изображение. Больше её не просят.
    ///
    /// Не просто «снять с ожидания», потому что причина здесь не про попытку:
    /// тот же ответ приедет и в следующий раз. А переспрашивать её нельзя ещё
    /// и потому, что ступень тогда не сдвинется никогда — заказ будет
    /// закрываться кэшем, пересчёт спрашивать то же самое, и так по кругу.
    pub fn rejected(&mut self, addr: Addr) {
        self.inflight.remove(&addr);
        self.failed.insert(addr);
    }

    /// Тайл не лёг по нашей осечке, а не по своей негодности: ожидание
    /// снимается, и ячейка спросится заново следующим пересчётом.
    ///
    /// Второй раз подряд на той же ячейке — уже приговор. Осечка, повторяющаяся
    /// на одном и том же месте, ничем не отличается от свойства этого места, а
    /// переспрашивание без конца звало бы производителя по кругу — то же
    /// правило и по тому же доводу, что у прощения сорвавшегося прохода
    /// ([`Fetch::produced`]).
    ///
    /// Подряд — это и значит подряд: приехавший тайл отметку снимает
    /// ([`Fetch::arrived`]), а смена источника уносит её вместе со всем прочим
    /// ([`Fetch::reset`]). Иначе ячейка, споткнувшаяся однажды и с тех пор
    /// исправно приезжавшая, приговаривалась бы за вторую осечку через час.
    /// Отвечает, стал ли этот заход приговором: приговорённая ячейка перестаёт
    /// держать ступень, то есть ход добычи меняется, а сказать об этом
    /// хранилищу нечем — непринятый тайл в него не лёг и счётчика не сдвинул.
    pub fn stumbled(&mut self, addr: Addr) -> bool {
        self.inflight.remove(&addr);
        let sentenced = !self.stumbled.insert(addr);
        if sentenced {
            self.failed.insert(addr);
        }
        sentenced
    }

    /// Проход кончился, чем бы он ни кончился. `failed` — сорвался: эти ячейки
    /// больше не просят, иначе каждый сдвиг камеры звал бы производителя за тем
    /// же отказом.
    ///
    /// Приговор при этом не вечный. Сорваться проход может от чего угодно —
    /// оборвалось чтение, не выделилась текстура, — и такой сбой проходит сам;
    /// а держись он до переоткрытия вкладки, в резком снимке оставалось бы
    /// мутное пятно, вылечить которое можно только случайно. Поэтому удачный
    /// проход по тому же источнику снимает приговор: сбой был у прохода, а не у
    /// ячейки. Второй раз подряд — уже свойство самой ячейки, и её оставляют;
    /// иначе безнадёжная ячейка переспрашивалась бы после каждого удачного
    /// прохода соседей.
    pub fn produced(&mut self, cells: &[Addr], failed: bool) {
        self.forget_asked(cells);
        match failed {
            true => self.failed.extend(cells.iter().copied()),
            false => self.forgive(),
        }
    }

    /// Простить тем, кому второго захода ещё не давали.
    fn forgive(&mut self) {
        let mut retried = std::mem::take(&mut self.retried);
        self.failed.retain(|addr| !retried.insert(*addr));
        self.retried = retried;
    }
}

/// Почему тайл не лёг — и, главное, надо ли спрашивать его заново.
///
/// Различаются здесь не тексты, а места, и правило то же, каким кэш разводит
/// свои промахи (`Miss::NoFile` против `Miss::Broken`). Пустая текстура и
/// нулевые размеры — свойство самого ответа: тот же ответ приедет и в
/// следующий раз, а переспрашивание звало бы производителя по кругу за одним и
/// тем же отказом. Вид же и привязка делаются здесь и сейчас, и отказать они
/// могут от нехватки видеопамяти — такое проходит само, а ячейка,
/// приговорённая за это, оставляет в резком снимке мутное пятно до самого
/// переоткрытия вкладки.
pub(crate) enum Unlanded {
    /// Ответ негоден: больше не просить.
    Answer(String),
    /// Попытка не удалась: снять с ожидания и спросить заново.
    Attempt(String),
}

/// Что делать с ячейкой после ответа про неё.
///
/// Названными исходами, а не булевым «лёг или нет»: тот сводил бы негодный
/// ответ и нашу осечку в один приговор, а поступать с ними надо по-разному.
pub enum Landing {
    Landed,
    /// Спросить заново: осечка была наша.
    Retry,
    /// Больше не просить: негоден сам ответ.
    Verdict,
}

/// Терминальный ответ, договорённый хостом, — это отказ, а не успех.
///
/// Пустой ответ читается как удача: у `QueryDone` пустые промахи значат «всё
/// нашлось», у `ProduceDone` пустая ошибка — «прошло». А договаривает его хост
/// там, где исполнитель умер посреди работы либо подписчика у запроса не
/// нашлось вовсе (см. [`veldsdk::answered_by_host`]) — и заказчик, принявший
/// это за удачу, снимает с ожидания ячейки, которых никто не привозил. Ступень
/// после этого не достроится никогда: ожидания висят, пересчёт их не спросит
/// заново, а полоса хода объявит «готово» над дырой в снимке.
///
/// Одно правило на обоих потребителей и на оба терминальных ответа: вопрос у
/// них один, а разойдясь, они дали бы разное поведение канвы и шара над одной
/// и той же бедой.
///
/// `None` — ответ настоящий, каким бы он ни был.
pub fn undelivered(error: &str) -> Option<String> {
    (error.is_empty() && veldsdk::answered_by_host())
        .then(|| "исполнитель не довёл работу: ответ договорил хост".to_string())
}

/// Чем кончился разбор промахов кэша ([`Fetch::missed`]).
///
/// Названными исходами, а не пустым списком: пустота значила бы сразу две
/// разные вещи, и та, о которой забыли, останавливала бы добычу молча.
pub enum Missed {
    /// За этими ячейками — к производителю.
    Produce(Vec<Addr>),
    /// Идти некуда и ждать нечего: кэш закрыл заказ целиком либо остальное
    /// уехало с глаз. Ступень тем самым пройдена, и спросить следующую надо
    /// здесь же. Иначе цикл «ступень доехала → просим следующую» замыкается
    /// только через конец прохода производителя, которого не было, и добыча
    /// встаёт до ближайшего движения камеры: снаружи это выглядит как «стоит
    /// мутным, а потом от одного щелчка становится резким».
    Closed,
    /// По источнику идёт проход. Ждём молча: сложенное им ляжет в кэш, а его
    /// конец пересчитает нужное всем, кто на этот источник смотрит.
    Waiting,
}

/// Проходы производителя: по одному на источник.
///
/// Один — потому что проход читает файл, и второй по тому же файлу не вторая
/// работа, а та же самая заново. Учёт поэтому и не у заказчика: заказчиков у
/// источника бывает несколько — две вкладки с одним снимком, два слоя одного
/// продукта, — а проход у них общий. Знать о нём обязаны все, иначе каждый
/// шлёт свой запрос кэшу, получает те же промахи и упирается в ту же очередь.
///
/// `K` — чем потребитель называет своих заказчиков: у канвы это имя вкладки, у
/// глобуса — слой и роль растра. Помнить его обязательно, потому что **проход
/// живёт ровно столько, сколько ресурс, который он читает**. Отпечаток у
/// заказчиков общий, а ресурсы у каждого свои: файл открывают порознь, и грант
/// тайлеру живёт не дольше самого ресурса. Уходящий заказчик поэтому свой
/// проход уносит с собой — сберечь его «для соседа» значит оставить чтение над
/// освобождённым ресурсом, то есть выбросить минуту работы и приписать соседу
/// чужую ошибку.
///
/// Убийство и снятие с учёта разведены по разным ключам, и это не случайность.
/// Убивают проход по его заказчику — «этому файл больше не нужен»; снимают с
/// учёта по корреляции — «кончился именно тот проход». Снимай мы по источнику,
/// поздний конец убитого прохода сносил бы запись нового, уже начатого по тому
/// же файлу.
pub struct Passes<K> {
    by_source: HashMap<String, Pass<K>>,
    /// Корреляции проходов, которые сняли мы сами.
    ///
    /// Хост договаривает терминальный ответ за снятого ровно тем же пустым
    /// сообщением, каким отвечает за упавшего, и различить их конвертом нельзя
    /// никогда: `dispatcher::kill` и `plugins::answer_for_lost` публикуют
    /// одинаково (см. [`undelivered`]). Различить может только тот, кто снимал.
    ///
    /// Помнится это здесь, рядом с самим снятием: у зовущего оба конца —
    /// снятие и приход ответа — лежат в разных обработчиках, и память,
    /// заведённая между ними, разошлась бы с тем, что снято на самом деле.
    killed: HashSet<String>,
}

struct Pass<K> {
    /// Корреляция запроса — ею же его и убивают.
    correlation: String,
    /// Уровень, ради которого проход затеян.
    level: u32,
    /// Кто его завёл.
    owner: K,
    /// Ячейки, ради которых проход затеян. Помнятся, чтобы отличить проход,
    /// который ещё пригодится, от проходящего мимо: уровнем этого не сказать
    /// (см. [`Pass::abandoned_by`]).
    cells: Vec<Addr>,
}

impl<K> Pass<K> {
    /// Проход не даёт этому взгляду ничего, и ждать его — потерянное время.
    ///
    /// Спрашивается это ячейками, а не уровнем, и разница здесь несущая. По
    /// уровню отличить нельзя: ступень грубее нынешней — это ровно то, чем
    /// пирамида и набирается, и объявив такой проход лишним, мы выбрасывали бы
    /// каждую пройденную ступень. Ячейки отвечают точно: пройденная ступень
    /// нужна, пока её тайлы — предки нынешних ячеек, и не нужна, когда ни один
    /// из них не подходит ни под одну. Случается это не только от сдвига
    /// камеры: приближение вчетверо в ту же самую точку оставляет за кадром
    /// краевые ячейки прежней ступени, и заказанный по ним проход становится
    /// работой в пустоту ровно так же.
    ///
    /// **Только там, где проход отдаёт ровно заказанное** ([`pointwise`]).
    /// Иначе один проход кладёт в кэш всю пирамиду либо ступень и всё грубее
    /// неё — то есть и то место, куда взгляд ушёл, — и посылка «он ничего не
    /// даст» неверна. Цена ошибки как раз там и наибольшая: убийство роняет
    /// инстанс тайлера, и прочитанный целиком NetCDF пришлось бы читать заново.
    ///
    /// Ступень **подробнее** нынешней сюда не идёт вовсе: она либо сама цель,
    /// либо обнажившийся край, и объявить её лишней значило бы выбросить
    /// только что заказанное.
    ///
    /// Пустой взгляд — не повод: считать по нему нечего (нет места под кадр,
    /// слой скрыт), и всякий проход выглядел бы лишним.
    fn abandoned_by(&self, want: &Want, pointwise: bool) -> bool {
        if !pointwise {
            return false;
        }
        // Пустые с любой стороны — судить нечем: о ячейках прохода не сказано
        // либо считать по взгляду нечего.
        if self.level <= want.level || want.cells.is_empty() || self.cells.is_empty() {
            return false;
        }
        let up = self.level - want.level;
        let covering: HashSet<Addr> =
            want.cells.iter().map(|&(_, x, y)| (self.level, x >> up, y >> up)).collect();
        !self.cells.iter().any(|cell| covering.contains(cell))
    }
}

impl<K> Default for Passes<K> {
    fn default() -> Self {
        Self { by_source: HashMap::new(), killed: HashSet::new() }
    }
}

impl<K: PartialEq> Passes<K> {
    /// По источнику идёт проход — спрашивать по нему нечего до его конца.
    pub fn going(&self, fingerprint: &str) -> bool {
        self.by_source.contains_key(fingerprint)
    }

    /// Идущий проход — наш: его конец придёт к нам, и на него можно ждать.
    /// Чужого конца мы не увидим (см. [`Fetch::missed`]).
    pub(crate) fn mine(&self, fingerprint: &str, owner: &K) -> bool {
        self.by_source.get(fingerprint).is_some_and(|pass| &pass.owner == owner)
    }

    /// Проход начат.
    pub fn begin(
        &mut self,
        fingerprint: &str,
        owner: K,
        correlation: String,
        level: u32,
        cells: Vec<Addr>,
    ) {
        self.by_source
            .insert(fingerprint.to_string(), Pass { correlation, level, owner, cells });
    }

    /// Проход, ставший бесполезным: он производит уровень **подробнее** того,
    /// который смотрят сейчас, — такими тайлами грубую ячейку не нарисовать.
    /// Отдаёт его корреляцию; убивает её вызывающий, у него для этого свой
    /// `cancel`.
    ///
    /// Проход грубее нужного не убивается, и это не поблажка: ячейка рисуется
    /// ближайшим имеющимся предком, то есть тайлом любого уровня выше, — а
    /// один щелчок колеса растянут инерцией на секунду и меняет уровень по
    /// нескольку раз. Убивая проход на каждой смене, мы выбрасывали бы
    /// наполовину прочитанный файл столько же раз за одно приближение.
    ///
    /// По той же причине снимает его только заведший. Проход общий, а уровень
    /// у заказчиков свой: соседняя вкладка того же снимка, отъехавшая на шаг,
    /// иначе выбрасывала бы чужое наполовину прочитанное чтение — и тут же
    /// заводила своё, которое так же выбросили бы в ответ.
    ///
    /// Сравнивается с **целью**, а не со ступенью, и `Want` берётся целиком
    /// ровно поэтому: ступень идёт от вершины к цели и отступает от всякого
    /// мелкого движения камеры, а обнажившаяся на ней ячейка объявляла бы
    /// устаревшим проход по самой цели — то есть работу, которую только что
    /// и заказали.
    ///
    /// Цена размена: пока проход идёт, [`Fetch::missed`] держит весь источник
    /// в ожидании, и обнажившийся грубый край стои́т предком до конца прохода,
    /// а не заливается заново. Куплено этим то, что недочитанный хвост не
    /// выбрасывается.
    ///
    /// Второй повод — проход, производящий место, на которое больше никто не
    /// смотрит ([`Pass::abandoned_by`]), и только у источника, отдающего ровно
    /// заказанное. Ждать его нечего вдвойне: он и сам ничего не даст, и держит
    /// за собой весь источник — заказ, оформленный вслед за ним, простаивает до
    /// его конца, а взгляд за это время уходит ещё дальше, и половина
    /// заказанного выбрасывается неспрошенной.
    pub fn stale(
        &mut self,
        fingerprint: &str,
        owner: &K,
        want: &Want,
        pointwise: bool,
    ) -> Option<String> {
        let stale = self.by_source.get(fingerprint).is_some_and(|pass| {
            &pass.owner == owner
                && (pass.level < want.target || pass.abandoned_by(want, pointwise))
        });
        match stale {
            true => {
                let taken = self.by_source.remove(fingerprint).map(|p| p.correlation);
                self.remembered(taken)
            }
            false => None,
        }
    }

    /// Заказчик уходит — со снимка, из вкладки, с шара: отдаёт корреляцию его
    /// прохода, если тот идёт. Убивает её вызывающий, у него для этого свой
    /// `cancel`.
    ///
    /// Чужой проход не трогается, и ждать от этого нечего: сосед читает свой
    /// ресурс, который никуда не делся. А вот свой уносится обязательно —
    /// ресурс под ним сейчас освободят (см. заголовок [`Passes`]).
    pub fn abandon(&mut self, fingerprint: &str, owner: &K) -> Option<String> {
        let ours = self.by_source.get(fingerprint).is_some_and(|pass| &pass.owner == owner);
        match ours {
            true => {
                let taken = self.by_source.remove(fingerprint).map(|p| p.correlation);
                self.remembered(taken)
            }
            false => None,
        }
    }

    /// Отдать корреляцию зовущему и запомнить, что снимаем её мы.
    ///
    /// Одним ходом с отдачей: два места, отдающих корреляцию на снятие, и
    /// третье, помнящее об этом, разошлись бы на первой же новой ветке — а
    /// цена расхождения тихая, ответ за снятое прочитался бы срывом.
    fn remembered(&mut self, correlation: Option<String>) -> Option<String> {
        if let Some(correlation) = &correlation {
            self.killed.insert(correlation.clone());
        }
        correlation
    }

    /// Проход кончился, чем бы он ни кончился. По корреляции, а не по
    /// источнику: заказчика могли закрыть, а проход по тому же файлу успеть
    /// начать заново.
    ///
    /// Отвечает, снимали ли этот проход мы сами. Ответ нужен ровно затем, чтобы
    /// не прочесть своё же снятие срывом: пустой терминал от хоста одинаков у
    /// снятого и у упавшего (см. [`undelivered`]), а поступать с ними надо
    /// по-разному — упавший это беда, снятое нами — обычный ход приближения.
    ///
    /// Спрашивается один раз: ответ за снятый проход приходит один, и память о
    /// нём здесь же и кончается.
    pub fn finish(&mut self, correlation: &str) -> bool {
        self.by_source.retain(|_, pass| pass.correlation != correlation);
        self.killed.remove(correlation)
    }
}

