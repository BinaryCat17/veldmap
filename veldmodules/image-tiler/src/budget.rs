//! Память инстанса: один лимит, из которого выведены потолки адаптеров.
//!
//! Потолков у тайлера много — у величины NetCDF, у прохода JPEG 2000, у полосы
//! TIFF, у кэша чанков, у решёток координат, — и делят они одну линейную память
//! одного инстанса. Пока каждый выводился из неё на глаз, числа расходились
//! молча: запас, оставленный одним, оказывался меньше того, что берёт другой, и
//! узнавалось это трапом посреди чтения.
//!
//! Здесь названо то единственное, что знать обязательно, — сколько памяти
//! дают, — а всё прочее выводится из него счётом. Считать умеет тот, кто тратит:
//! [`crate::cascade::bytes`] знает цену полос, `netcdf::peak_per_pixel` — цену
//! развёртки. Здесь только вычитание.

/// Сколько линейной памяти хост даёт одному инстансу.
///
/// Копия `INSTANCE_MEMORY_LIMIT` из ядра хоста, и копия поневоле: числа лежат по
/// разные стороны провода, хостовой константы модулю не видно. Равенство держит
/// тест сборки `test_tiler_budgets.py` — компилятор такую пару не свяжет, а
/// рантайм свяжет трапом.
pub const INSTANCE: u64 = 1024 * 1024 * 1024;

/// Занятое всегда и никем не считаемое.
///
/// Сюда входят код модуля со своей статикой, стек, кэш заголовков HDF5
/// (`netcdf::METADATA_CACHE`, восемь мегабайт) и провисание аллокатора:
/// отпущенное крупное возвращается ему, но не хосту, и следующий крупный запрос
/// обязан лечь в освободившуюся дыру. Не ляжет непрерывным куском — будет
/// `memory.grow` и трап при формально свободных сотнях мегабайт.
///
/// Число это назначено, а не выведено, и в этом оно честнее прежних: прежние
/// тоже были назначены, но каждое поодиночке и каждое молча.
pub const RESERVE: u64 = 96 * 1024 * 1024;

/// Сколько остаётся работе над источником.
pub const fn free() -> u64 {
    INSTANCE - RESERVE
}

/// Байты в мегабайтах для разговора с человеком.
pub fn mb(bytes: u64) -> u64 {
    bytes / (1024 * 1024)
}

#[cfg(test)]
mod tests {
    use super::*;
    use super::super::cascade;

    /// Запас не съедает лимит целиком: иначе всякий источник отвергался бы.
    #[test]
    fn запас_оставляет_место_работе() {
        assert!(RESERVE < INSTANCE / 2, "запас {} съел половину лимита", RESERVE);
        assert!(free() > 0);
    }

    /// Каскад на самой широкой стороне, какую тайлер вообще берёт, помещается в
    /// остаток. Это та пара, ради которой учёт и заведён: цену каскада знает
    /// `cascade`, потолок стороны — `adapters`, а складывал их до сих пор
    /// никто.
    #[test]
    fn каскад_предельной_ширины_помещается() {
        let side = super::super::adapters::MAX_SOURCE_SIDE;
        let need = cascade::bytes(side, side);
        assert!(
            need < free(),
            "каскад {}×{} просит {} МБ при свободных {} МБ",
            side, side, mb(need), mb(free())
        );
    }

    /// Плоскость величины и каскад по ней вместе помещаются в остаток. Порознь
    /// они помещались и раньше — расходилось именно сложение.
    #[test]
    fn плоскость_вместе_со_своим_каскадом_помещается() {
        // Самый дорогой случай: величина занимает весь остаток, какой ей
        // оставляет её же каскад. Проверяем, что такая пара существует, — то
        // есть что вычитание не ушло в ноль.
        for (w, h) in [(4865u32, 4091u32), (15076, 1217), (10980, 10980)] {
            let plane = u64::from(w) * u64::from(h) * 4;
            let need = plane + cascade::bytes(w, h);
            assert!(
                need < free(),
                "растр {}×{}: плоскость {} МБ и каскад {} МБ при свободных {} МБ",
                w, h, mb(plane), mb(cascade::bytes(w, h)), mb(free())
            );
        }
    }
}
