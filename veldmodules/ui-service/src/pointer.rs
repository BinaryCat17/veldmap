//! Номера кнопок мыши: `1` — левая, `2` — правая, `3` — средняя.
//!
//! Так они названы и в `ClickEvent` (app.proto, ввод от хоста), и в
//! `PointerEvent` (types.proto, событие области владельцу разметки), и ходят
//! по этой таблице в обе стороны. Написанные порознь, две таблицы совпадают
//! ровно до первой правки.

use iced_core::mouse::Button;

/// Номер кнопки в терминах протокола. `None` — кнопка, которой в нём нет:
/// боковые и прочие сверх трёх основных.
pub fn to_index(button: Button) -> Option<u32> {
    match button {
        Button::Left => Some(1),
        Button::Right => Some(2),
        Button::Middle => Some(3),
        _ => None,
    }
}

/// Обратно. `None` — номер, которому кнопки не сопоставлено; такое событие
/// проще уронить, чем истолковать. Подстановка левой на этом месте означала
/// бы, что боковая кнопка мыши нажимает то, на что наведён курсор.
pub fn from_index(index: u32) -> Option<Button> {
    match index {
        1 => Some(Button::Left),
        2 => Some(Button::Right),
        3 => Some(Button::Middle),
        _ => None,
    }
}
