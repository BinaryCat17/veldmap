//! Типографика ui-service: логические имена шрифтов и кегль по умолчанию.
//!
//! Единственный экземпляр, общий с wrap-крейтом: файл включается и сюда, и в
//! `wraps/rust/src/wrap.rs` через `#[path]`. Здесь он потому, что регистрирует
//! шрифты и чинит негодный кегль ui-service, а не его клиент.
//!
//! Имена — строковый контракт: под ними ui-service кладёт файлы шрифтов
//! (`state.rs`), ими же клиент называет шрифт виджета. Кегль — умолчание с двух
//! сторон сразу: им клиент собирает текст, не назвав размера, и им же
//! ui-service заменяет присланный негодным. Разъехавшись, эти два числа дали бы
//! разный текст на одну и ту же разметку.
//!
//! У одного имени бывает несколько файлов: начертания — это разные лица одного
//! семейства, и выбирает между ними уже вес текста (`Text.weight`). Без своего
//! файла вес подменяется ближайшим.
//!
//! Всё, что из `crate::`, сломало бы включение в wrap молча, а библиотека здесь
//! годится только объявленная обоим — и модулю, и wrap-крейту
//! (`rust.wrap_dependencies` в config.yaml). Сейчас файлу не нужно ни той, ни
//! другой: он про строки и одно число.

/// Шрифт подписей и заголовков, он же дефолтный.
pub const FONT_UI: &str = "UI";
/// Там, где важна одинаковая ширина знака: имена файлов, размеры, пути.
pub const FONT_MONO: &str = "Mono";
/// Глифы значков.
pub const FONT_ICONS: &str = "Icons";

/// Кегль текста, которому размера не назвали.
pub const DEFAULT_TEXT_SIZE: f32 = 16.0;
